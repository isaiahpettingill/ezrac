// Reserve four bytes at the bottom of ATmega SRAM for indirect source and
// destination pointers. 0x00F0 is USB endpoint register space on ATmega32U4.
const POINTER_ZP: u32 = 0x0100;

pub fn emit_avr_assembly_with_options(
    program: &Program,
    options: AssemblyOptions,
) -> Result<String, Diagnostic> {
    if options.cpu != CpuFamily::Avr {
        return Err(Diagnostic::new("AVR emitter requires an AVR target"));
    }
    if program.main_function().is_none() {
        return Err(Diagnostic::new("AVR programs require a `main` function"));
    }
    let hir = HirProgram::from_ast(program)?;
    let (lowered_program, source_comments) = if contains_function_pointer_program(program) {
        (program.clone(), Vec::new())
    } else {
        let tbir = TbirProgram::lower(&hir, program, &options)?;
        (tbir.lowered_program, tbir.source_comments)
    };
    let model = SemanticModel::from_program(
        &lowered_program,
        16,
        options.ram_base.get(),
        options.rodata_base.get(),
        options.asset_base.get(),
    )?;
    Emitter::new(model, options.clone())
        .emit(&lowered_program)
        .map(|asm| {
            let asm = if options
                .optimization
                .is_enabled(crate::optimization::OptimizationPass::RedundantRegisterCopies)
            {
                crate::asm::copy_cleanup::remove_redundant_register_copies(&asm, options.cpu)
            } else {
                asm
            };
            let asm = if options
                .optimization
                .is_enabled(crate::optimization::OptimizationPass::DeadCodeElimination)
            {
                strip_unreachable_generated_routines(&asm, RoutineProfile::Avr)
            } else {
                asm
            };
            with_readability_comments(asm, program, &options, "avr", &source_comments)
        })
}

#[derive(Clone)]
enum BindingLocation {
    Register(Vec<u8>),
    Storage(Storage),
}

#[derive(Clone)]
struct Binding {
    location: BindingLocation,
    ty: Type,
}

struct FunctionLocals {
    bindings: HashMap<String, Binding>,
}

#[derive(Clone)]
struct LoopLabels {
    continue_label: String,
    break_label: String,
}

struct Emitter {
    model: SemanticModel,
    out: String,
    labels: usize,
    scopes: Vec<HashMap<String, Binding>>,
    loops: Vec<LoopLabels>,
    return_labels: Vec<String>,
    return_types: Vec<Option<Type>>,
    second_return_types: Vec<Option<Type>>,
    second_return_pointers: Vec<Option<Storage>>,
    function_ram_bases: Vec<u32>,
    function_pointer_values: HashMap<String, Storage>,
    r0: Storage,
    r1: Storage,
    r2: Storage,
    arduboy_executable: bool,
}

impl Emitter {
    fn new(mut model: SemanticModel, options: AssemblyOptions) -> Self {
        let r0 = model.allocate(4).expect("AVR result scratch allocation");
        let r1 = model.allocate(4).expect("AVR rhs scratch allocation");
        let r2 = model.allocate(4).expect("AVR work scratch allocation");
        Self {
            model,
            out: String::new(),
            labels: 0,
            scopes: Vec::new(),
            loops: Vec::new(),
            return_labels: Vec::new(),
            return_types: Vec::new(),
            second_return_types: Vec::new(),
            second_return_pointers: Vec::new(),
            function_ram_bases: Vec::new(),
            function_pointer_values: HashMap::new(),
            r0,
            r1,
            r2,
            arduboy_executable: options.arduboy_executable,
        }
    }

    fn emit(mut self, program: &Program) -> Result<String, Diagnostic> {
        self.validate_function_signatures(program)?;
        self.line("; generated by ezrac");
        self.line("; target: AVR register ABI");
        self.line("section .text");
        if self.arduboy_executable {
            self.emit_arduboy_vector_table(program)?;
        }
        self.line("__ezra_start:");
        self.line("    cli");
        self.line("    ldi r16, FFh");
        self.line("    out 3Dh, r16");
        self.line("    ldi r16, 0Ah");
        self.line("    out 3Eh, r16");
        self.line("    clr r1");
        self.prepare_function_pointer_values(program)?;
        self.emit_function_pointer_initializers()?;
        self.emit_static_initializers(program)?;
        self.line("    call _main");
        self.line("__ezra_exit:");
        self.line("    jmp __ezra_exit");

        let mut emitted_functions = reachable_function_names(program, &self.model);
        // Inline assembly can reference function symbols that are intentionally opaque to
        // source-level call analysis, so retain every declared function for link correctness.
        emitted_functions.extend(program.declarations.iter().filter_map(|declaration| {
            if let Declaration::Function(function) = declaration {
                Some(function.name.clone())
            } else {
                None
            }
        }));
        for declaration in &program.declarations {
            if let Declaration::Function(function) = declaration
                && emitted_functions.contains(&function.name)
                // Imported qualified names are semantic aliases of their
                // short labels. Emitting both duplicates the SDK routine and
                // can exceed constrained AVR application flash.
                && !function.name.contains('.')
            {
                self.emit_function(function)?;
            }
        }
        for declaration in &program.declarations {
            let Declaration::Function(function) = declaration else {
                continue;
            };
            let Some((_, short_name)) = function.name.rsplit_once('.') else {
                continue;
            };
            if emitted_functions.contains(&function.name) {
                self.line(&format!("{}:", function_label(&function.name)));
                self.line(&format!("    jmp {}", function_label(short_name)));
            }
        }
        if self.arduboy_executable {
            self.line("__ezra_unhandled_interrupt:");
            self.line("    cli");
            self.line("    rjmp __ezra_unhandled_interrupt");
        }
        for section in [".header", ".rodata", ".data", ".bss", ".assets", ".scratch"] {
            self.line(&format!("section {section}"));
        }
        Ok(self.out)
    }

    fn emit_arduboy_vector_table(&mut self, program: &Program) -> Result<(), Diagnostic> {
        const HANDLERS: [Option<&str>; 32] = [
            None,
            Some("avr_int0"),
            Some("avr_int1"),
            Some("avr_int2"),
            Some("avr_int3"),
            Some("avr_int6"),
            Some("avr_pcint0"),
            Some("avr_usb_gen"),
            Some("avr_usb_com"),
            Some("avr_wdt"),
            Some("avr_timer1_capt"),
            Some("avr_timer1_compa"),
            Some("avr_timer1_compb"),
            Some("avr_timer1_compc"),
            Some("avr_timer1_ovf"),
            Some("avr_timer0_compa"),
            Some("avr_timer0_compb"),
            Some("avr_timer0_ovf"),
            Some("avr_spi_stc"),
            Some("avr_usart1_rx"),
            Some("avr_usart1_udre"),
            Some("avr_usart1_tx"),
            Some("avr_analog_comp"),
            Some("avr_adc"),
            Some("avr_ee_ready"),
            Some("avr_timer3_capt"),
            Some("avr_timer3_compa"),
            Some("avr_timer3_compb"),
            Some("avr_timer3_compc"),
            Some("avr_timer3_ovf"),
            Some("avr_twi"),
            Some("avr_spm_ready"),
        ];

        let declared = program
            .declarations
            .iter()
            .filter_map(|declaration| match declaration {
                Declaration::Function(function) => Some(function),
                _ => None,
            })
            .collect::<Vec<_>>();
        for function in &declared {
            let interrupt = function.attrs.iter().any(|attr| attr == "interrupt");
            let vector_name = HANDLERS.iter().flatten().any(|name| *name == function.name);
            if vector_name && !interrupt {
                return Err(Diagnostic::new(format!(
                    "Arduboy vector handler `{}` must be declared `interrupt fn`",
                    function.name
                )));
            }
            if interrupt && !vector_name {
                return Err(Diagnostic::new(format!(
                    "Arduboy interrupt function `{}` must use one of the documented `avr_*` vector handler names",
                    function.name
                )));
            }
        }

        self.line("; ATmega32U4 interrupt vectors: 32 absolute 4-byte JMP entries");
        for (slot, handler) in HANDLERS.iter().enumerate() {
            let target = if slot == 0 {
                "__ezra_start"
            } else if let Some(name) = handler
                && declared.iter().any(|function| function.name == *name)
            {
                &function_label(name)
            } else {
                "__ezra_unhandled_interrupt"
            };
            self.line(&format!("    jmp {target}"));
        }
        Ok(())
    }

    fn emit_interrupt_prologue(&mut self) {
        // AVR hardware clears I on entry. Preserve every GPR plus SREG and the
        // shared compiler scratch bytes so an ISR can safely preempt generated code.
        self.line("    push r0");
        self.line("    in r0, 3Fh");
        self.line("    cli");
        self.line("    push r0");
        for register in 1..=31 {
            self.line(&format!("    push r{register}"));
        }
        for storage in [self.r0, self.r1, self.r2] {
            for offset in 0..storage.size {
                self.line(&format!("    lds r0, {:04X}h", storage.address + offset));
                self.line("    push r0");
            }
        }
        for offset in 0..4 {
            self.line(&format!("    lds r0, {:04X}h", POINTER_ZP + offset));
            self.line("    push r0");
        }
        self.line("    clr r1");
    }

    fn emit_interrupt_epilogue(&mut self) {
        for offset in (0..4).rev() {
            self.line("    pop r0");
            self.line(&format!("    sts {:04X}h, r0", POINTER_ZP + offset));
        }
        for storage in [self.r2, self.r1, self.r0] {
            for offset in (0..storage.size).rev() {
                self.line("    pop r0");
                self.line(&format!("    sts {:04X}h, r0", storage.address + offset));
            }
        }
        for register in (1..=31).rev() {
            self.line(&format!("    pop r{register}"));
        }
        self.line("    pop r0");
        self.line("    out 3Fh, r0");
        self.line("    pop r0");
    }

    fn validate_function_signatures(&self, program: &Program) -> Result<(), Diagnostic> {
        for declaration in &program.declarations {
            let (name, return_type, second_return_type, is_extern) = match declaration {
                Declaration::Function(function) => (
                    &function.name,
                    &function.return_type,
                    &function.second_return_type,
                    false,
                ),
                Declaration::ExternAsmFunction(function) => (
                    &function.name,
                    &function.return_type,
                    &function.second_return_type,
                    true,
                ),
                _ => continue,
            };
            if let Some(second_return_type) = second_return_type {
                if return_type.is_none() {
                    return Err(Diagnostic::new(format!(
                        "AVR two-result function `{name}` must have a first return type"
                    )));
                }
                if is_extern {
                    return Err(Diagnostic::new(format!(
                        "AVR extern asm function `{name}` cannot use two-result returns"
                    )));
                }
                self.model.type_width(second_return_type)?;
            }
        }
        Ok(())
    }

    fn emit_static_initializers(&mut self, program: &Program) -> Result<(), Diagnostic> {
        let embeds = self.model.embeds.values().cloned().collect::<Vec<_>>();
        for embed in embeds {
            for (offset, byte) in embed.bytes.iter().copied().enumerate() {
                self.lda_imm(byte);
                self.sta(embed.storage.address + offset as u32);
            }
        }
        let strings = self
            .model
            .strings
            .iter()
            .map(|(value, storage)| (value.clone(), *storage))
            .collect::<Vec<_>>();
        for (value, storage) in strings {
            for (offset, byte) in value.bytes().chain(core::iter::once(0)).enumerate() {
                self.lda_imm(byte);
                self.sta(storage.address + offset as u32);
            }
        }
        for declaration in &program.declarations {
            match declaration {
                Declaration::Global(global) => {
                    let storage = self.model.globals[&global.name];
                    self.emit_initializer(storage, &global.ty, &global.value)?;
                }
                Declaration::Const(constant) if matches!(constant.ty, Type::Array { .. }) => {
                    let storage = self.model.globals[&constant.name];
                    self.emit_initializer(storage, &constant.ty, &constant.value)?;
                }
                _ => {}
            }
        }
        Ok(())
    }

    fn prepare_function_pointer_values(&mut self, program: &Program) -> Result<(), Diagnostic> {
        let mut names = Vec::new();
        for declaration in &program.declarations {
            match declaration {
                Declaration::Function(function) => {
                    collect_stmt_function_references(&function.body, &mut names);
                }
                Declaration::Global(global) => {
                    collect_expr_function_references(&global.value, &mut names);
                }
                _ => {}
            }
        }
        names.sort();
        names.dedup();
        for name in names {
            if self
                .model
                .functions
                .get(&name)
                .is_some_and(|signature| signature.second_return_type.is_none())
            {
                let storage = self.model.allocate(2)?;
                self.function_pointer_values.insert(name, storage);
            }
        }
        Ok(())
    }

    fn emit_function_pointer_initializers(&mut self) -> Result<(), Diagnostic> {
        let mut initializers = self
            .function_pointer_values
            .iter()
            .map(|(name, storage)| (name.clone(), *storage))
            .collect::<Vec<_>>();
        initializers.sort_by(|left, right| left.0.cmp(&right.0));
        for (name, storage) in initializers {
            let capture_label = self.next_label("function_pointer_capture");
            let trampoline_label = self.next_label("function_pointer_trampoline");
            let after_label = self.next_label("function_pointer_after");

            // AVR CALL leaves the word address of the following instruction on
            // the stack. Put the trampoline there and capture that address
            // without linker-specific low/high symbol expressions.
            self.line(&format!("    call {capture_label}"));
            self.line(&format!("{trampoline_label}:"));
            self.line(&format!("    jmp {}", function_label(&name)));
            self.line(&format!("{capture_label}:"));
            self.line("    pop r30");
            self.line("    pop r31");
            self.line(&format!("    sts {:04X}h, r30", self.r0.address));
            self.line(&format!("    sts {:04X}h, r31", self.r0.address + 1));
            self.line(&format!("    jmp {after_label}"));
            self.line(&format!("{after_label}:"));
            self.copy(self.r0, storage, 2);
        }
        Ok(())
    }

    fn emit_function_pointer_value(&mut self, name: &str) -> Result<(), Diagnostic> {
        let storage = self
            .function_pointer_values
            .get(name)
            .copied()
            .ok_or_else(|| Diagnostic::new(format!("unknown function `{name}`")))?;
        self.copy(storage, self.r0, 2);
        Ok(())
    }

    fn function_value_type(&self, name: &str) -> Option<Type> {
        self.model
            .functions
            .get(name)
            .filter(|signature| signature.second_return_type.is_none())
            .map(|signature| Type::Function {
                params: signature.params.clone(),
                return_type: signature.return_type.clone().map(Box::new),
            })
    }

    fn emit_function(&mut self, function: &Function) -> Result<(), Diagnostic> {
        let return_label = self.next_label(&format!("{}_return", function.name));
        let naked = function.attrs.iter().any(|attr| attr == "naked");
        let interrupt = function.attrs.iter().any(|attr| attr == "interrupt");
        if interrupt
            && (!function.params.is_empty()
                || function.return_type.is_some()
                || function.second_return_type.is_some())
        {
            return Err(Diagnostic::new(format!(
                "interrupt function `{}` cannot have parameters or a return value",
                function.name
            )));
        }
        if function.second_return_type.is_none() && contains_two_result_statement(&function.body) {
            return Err(Diagnostic::new(format!(
                "AVR function `{}` contains a two-result statement without a two-result signature",
                function.name
            )));
        }
        if function.second_return_type.is_some()
            && block_can_complete_normally(&function.body, &self.model)
        {
            return Err(Diagnostic::new(format!(
                "function `{}` may fall through without returning two values",
                function.name
            )));
        }
        if naked && function.second_return_type.is_some() {
            return Err(Diagnostic::new(format!(
                "naked two-result function `{}` is not supported",
                function.name
            )));
        }
        if naked
            && function.body.iter().any(|stmt| {
                !matches!(
                    stmt,
                    Stmt::Asm {
                        inputs,
                        outputs,
                        ..
                    } if inputs.is_empty() && outputs.is_empty()
                )
            })
        {
            return Err(Diagnostic::new(format!(
                "naked function `{}` may contain only asm blocks without operands",
                function.name
            )));
        }
        let function_ram_base = self.model.next_ram_address();
        let second_return_pointer = function
            .second_return_type
            .as_ref()
            .map(|_| self.model.allocate(2))
            .transpose()?;
        let locals = plan_function_locals(function, &mut self.model)?;
        self.line(&format!("{}:", function_label(&function.name)));
        self.scopes.push(locals.bindings);
        self.return_labels.push(return_label.clone());
        self.return_types.push(function.return_type.clone());
        self.second_return_types
            .push(function.second_return_type.clone());
        self.second_return_pointers.push(second_return_pointer);
        self.function_ram_bases.push(function_ram_base);

        if interrupt && !naked {
            self.emit_interrupt_prologue();
        }
        if let Some(pointer) = second_return_pointer {
            self.line(&format!("    sts {:04X}h, r26", pointer.address));
            self.line(&format!("    sts {:04X}h, r27", pointer.address + 1));
        }
        let signature = self
            .model
            .functions
            .get(&function.name)
            .cloned()
            .ok_or_else(|| Diagnostic::new(format!("unknown function `{}`", function.name)))?;
        let argument_registers = self.argument_registers(&signature.params)?;
        for (index, param) in function.params.iter().enumerate() {
            let slot = signature.argument_slots[index];
            let size = self.model.type_size(&param.ty)?;
            if let Some(register) = argument_registers[index] {
                for offset in 0..size {
                    self.line(&format!(
                        "    sts {:04X}h, r{}",
                        slot.address + offset,
                        register + offset as u8
                    ));
                }
            }
            let storage = self.model.allocate_type(&param.ty)?;
            self.bind_storage(param.name.clone(), storage, param.ty.clone())?;
            self.copy(slot, storage, size);
        }
        self.emit_block(&function.body)?;
        self.line(&format!("{return_label}:"));
        if let Some(ty) = &function.return_type {
            for offset in 0..self.model.type_size(ty)? {
                self.line(&format!(
                    "    lds r{}, {:04X}h",
                    24 + offset,
                    self.r0.address + offset
                ));
            }
        }
        if interrupt {
            if !naked {
                self.emit_interrupt_epilogue();
            }
            self.line("    rti");
        } else if !naked {
            self.line("    rts");
        }

        self.second_return_pointers.pop();
        self.second_return_types.pop();
        self.return_types.pop();
        self.return_labels.pop();
        self.function_ram_bases.pop();
        self.scopes.pop();
        Ok(())
    }

    fn emit_block(&mut self, body: &[Stmt]) -> Result<(), Diagnostic> {
        for stmt in body {
            self.emit_stmt(stmt)?;
        }
        Ok(())
    }

    fn emit_stmt(&mut self, stmt: &Stmt) -> Result<(), Diagnostic> {
        self.line(&format!("    ; source: {}", stmt_summary(stmt)));
        match stmt {
            Stmt::Let { name, ty, value } => {
                let binding = self.binding(name)?;
                self.emit_binding_initializer(&binding, ty, value)?;
            }
            Stmt::LetTwo {
                first_name,
                first_ty,
                second_name,
                second_ty,
                value,
            } => {
                let first = self.binding(first_name)?;
                let second = self.binding(second_name)?;
                let second_storage =
                    self.binding_storage(&second, "store the second result of a two-result call")?;
                self.emit_two_result_call(value, first_ty, second_ty, second_storage)?;
                self.store_binding_result(&first)?;
            }
            Stmt::Assign { target, op, value } => {
                let ty = self.place_type(target)?;
                let Ok(width) = self.model.type_width(&ty) else {
                    if *op != AssignOp::Set {
                        return Err(Diagnostic::new(
                            "compound assignment requires a scalar value",
                        ));
                    }
                    let size = self.model.type_size(&ty)?;
                    let temporary = self.model.allocate(size)?;
                    self.emit_initializer(temporary, &ty, value)?;
                    self.emit_store_aggregate_place(target, temporary, size)?;
                    return Ok(());
                };
                if *op == AssignOp::Set {
                    self.emit_expr(value, &ty)?;
                } else {
                    self.emit_load_place(target, width)?;
                    let left = self.model.allocate(u32::from(width))?;
                    self.copy(self.r0, left, u32::from(width));
                    self.emit_expr(value, &ty)?;
                    self.copy(self.r0, self.r1, u32::from(width));
                    self.copy(left, self.r0, u32::from(width));
                    self.emit_binary_op(assign_binary(*op), width, false)?;
                }
                self.emit_store_place(target, width)?;
            }
            Stmt::If {
                condition,
                then_body,
                else_body,
            } => {
                let else_label = self.next_label("if_else");
                let end_label = self.next_label("if_end");
                self.emit_expr(condition, &Type::Named("bool".to_owned()))?;
                self.jump_if_zero(self.r0.address, &else_label);
                self.emit_block(then_body)?;
                self.line(&format!("    jmp {end_label}"));
                self.line(&format!("{else_label}:"));
                self.emit_block(else_body)?;
                self.line(&format!("{end_label}:"));
            }
            Stmt::While { condition, body } => {
                let condition_label = self.next_label("while_condition");
                let break_label = self.next_label("while_end");
                self.loops.push(LoopLabels {
                    continue_label: condition_label.clone(),
                    break_label: break_label.clone(),
                });
                self.line(&format!("{condition_label}:"));
                self.emit_expr(condition, &Type::Named("bool".to_owned()))?;
                self.jump_if_zero(self.r0.address, &break_label);
                self.emit_block(body)?;
                self.line(&format!("    jmp {condition_label}"));
                self.line(&format!("{break_label}:"));
                self.loops.pop();
            }
            Stmt::Loop { body } => {
                let continue_label = self.next_label("loop_body");
                let break_label = self.next_label("loop_end");
                self.loops.push(LoopLabels {
                    continue_label: continue_label.clone(),
                    break_label: break_label.clone(),
                });
                self.line(&format!("{continue_label}:"));
                self.emit_block(body)?;
                self.line(&format!("    jmp {continue_label}"));
                self.line(&format!("{break_label}:"));
                self.loops.pop();
            }
            Stmt::Break => {
                let label = self
                    .loops
                    .last()
                    .ok_or_else(|| Diagnostic::new("break outside loop"))?
                    .break_label
                    .clone();
                self.line(&format!("    jmp {label}"));
            }
            Stmt::Continue => {
                let label = self
                    .loops
                    .last()
                    .ok_or_else(|| Diagnostic::new("continue outside loop"))?
                    .continue_label
                    .clone();
                self.line(&format!("    jmp {label}"));
            }
            Stmt::Return(value) => {
                if self
                    .second_return_types
                    .last()
                    .and_then(Option::as_ref)
                    .is_some()
                {
                    return Err(Diagnostic::new(
                        "two-result function must use `return first, second`",
                    ));
                }
                if let Some(value) = value {
                    let ty = self
                        .return_types
                        .last()
                        .and_then(Clone::clone)
                        .ok_or_else(|| Diagnostic::new("value return in void function"))?;
                    self.emit_expr(value, &ty)?;
                }
                let label = self
                    .return_labels
                    .last()
                    .expect("function return label")
                    .clone();
                self.line(&format!("    jmp {label}"));
            }
            Stmt::ReturnTwo { first, second } => self.emit_return_two(first, second)?,
            Stmt::Asm {
                inputs,
                outputs,
                lines,
                ..
            } => self.emit_inline_asm(inputs, outputs, lines)?,
            Stmt::Out { port, .. } => {
                return Err(Diagnostic::new(format!(
                    "AVR does not support separate port I/O `{port}`; use mmio instead"
                )));
            }
            Stmt::Expr(expr) => {
                let ty = self.expr_type(expr).unwrap_or(Type::Named("u8".to_owned()));
                self.emit_expr(expr, &ty)?;
            }
        }
        Ok(())
    }

    fn emit_binding_initializer(
        &mut self,
        binding: &Binding,
        ty: &Type,
        value: &Expr,
    ) -> Result<(), Diagnostic> {
        if self.model.type_width(ty).is_ok() {
            self.emit_expr(value, ty)?;
            self.store_binding_result(binding)?;
            return Ok(());
        }
        let storage = self.binding_storage(binding, "initialize aggregate local")?;
        self.emit_initializer(storage, ty, value)
    }

    fn emit_initializer(
        &mut self,
        storage: Storage,
        ty: &Type,
        value: &Expr,
    ) -> Result<(), Diagnostic> {
        match (self.model.resolved_type(ty)?, value) {
            (Type::Array { .. }, Expr::Ident(name)) => {
                let source = self.binding(name)?;
                let source = self.binding_storage(&source, "copy aggregate local")?;
                self.copy(source, storage, storage.size);
            }
            (Type::Array { element, len }, Expr::Array(values)) => {
                let element_size = self.model.type_size(&element)?;
                let len = u32::try_from(self.model.const_value(&len)?)
                    .map_err(|_| Diagnostic::new("invalid array length"))?;
                for index in 0..len {
                    let target = Storage {
                        address: storage.address + index * element_size,
                        size: element_size,
                    };
                    if let Some(value) = values.get(index as usize) {
                        self.emit_initializer(target, &element, value)?;
                    } else {
                        self.zero(target);
                    }
                }
            }
            (Type::Named(name), Expr::StructInit { fields, .. })
                if self.model.structs.contains_key(&name) =>
            {
                self.zero(storage);
                let layout = self.model.structs[&name].clone();
                for (field_name, value) in fields {
                    let field = layout
                        .fields
                        .get(field_name)
                        .ok_or_else(|| Diagnostic::new(format!("unknown field `{field_name}`")))?;
                    self.emit_initializer(
                        Storage {
                            address: storage.address + field.offset,
                            size: field.size,
                        },
                        &field.ty,
                        value,
                    )?;
                }
            }
            (Type::Named(name), Expr::Ident(source)) if self.model.structs.contains_key(&name) => {
                let source = self.binding(source)?;
                let source = self.binding_storage(&source, "copy aggregate local")?;
                self.copy(source, storage, storage.size);
            }
            (resolved @ (Type::Array { .. } | Type::Named(_)), Expr::Deref(pointer)) => {
                self.emit_expr(pointer, &Type::Ptr(Box::new(resolved)))?;
                self.copy_result_to_zp();
                self.copy_indirect_to_storage(storage, storage.size);
            }
            (resolved, _) => {
                let width = self.model.type_width(&resolved)?;
                self.emit_expr(value, &resolved)?;
                self.copy(self.r0, storage, u32::from(width));
            }
        }
        Ok(())
    }

    fn emit_expr(&mut self, expr: &Expr, expected: &Type) -> Result<(), Diagnostic> {
        let width = self.model.type_width(expected)?;
        match expr {
            Expr::Int(value) | Expr::TypedInt(value, _) => self.load_constant(*value, width),
            Expr::Bool(value) => self.load_constant(i64::from(*value), width),
            Expr::Char(value) => self.load_constant(i64::from(*value), width),
            Expr::String(value) => {
                let storage = self.model.intern_string(value)?;
                self.load_constant(i64::from(storage.address), width);
            }
            Expr::Ident(name) => {
                if let Some(value) = self.model.constants.get(name).copied() {
                    self.load_constant(value, width);
                } else {
                    let binding = self.binding(name)?;
                    let source_width = self.model.type_width(&binding.ty)?;
                    self.load_binding_result(&binding)?;
                    self.extend_result(source_width, width, type_is_signed(&binding.ty));
                }
            }
            Expr::In(port) => {
                return Err(Diagnostic::new(format!(
                    "AVR does not support separate port I/O `{port}`; use mmio instead"
                )));
            }
            Expr::AddressOf(name) => {
                if let Some(function_ty) = self.function_value_type(name) {
                    let expected = self.model.resolved_type(expected)?;
                    let actual = Type::Ptr(Box::new(self.model.resolved_type(&function_ty)?));
                    if expected != actual {
                        return Err(Diagnostic::new(format!(
                            "function `{name}` has an incompatible function-pointer type"
                        )));
                    }
                    self.emit_function_pointer_value(name)?;
                } else if self
                    .model
                    .functions
                    .get(name)
                    .is_some_and(|signature| signature.second_return_type.is_some())
                {
                    return Err(Diagnostic::new(format!(
                        "AVR function pointer cannot reference two-result function `{name}`"
                    )));
                } else {
                    let binding = self.binding(name)?;
                    let storage =
                        self.binding_storage(&binding, "take address of register local")?;
                    self.load_constant(i64::from(storage.address), width);
                }
            }
            Expr::AddressOfIndex { name, index } => {
                self.emit_named_index_address(name, index)?;
                self.copy_zp_to_result(width);
            }
            Expr::AddressOfField { base, field } => {
                let binding = self.binding(base)?;
                let field = self.model.field(&binding.ty, field)?;
                let storage = self.binding_storage(&binding, "take address of register local")?;
                self.load_constant(i64::from(storage.address + field.offset), width);
            }
            Expr::AddressOfAccess(path) => {
                let (_, _) = self.emit_access_address(path)?;
                self.copy_zp_to_result(width);
            }
            Expr::Index { name, index } => {
                let element = self.emit_named_index_address(name, index)?;
                let element_width = self.model.type_width(&element)?;
                self.load_indirect(element_width);
                self.extend_result(element_width, width, false);
            }
            Expr::Field { base, field } => {
                let constant_name = format!("{base}.{field}");
                if let Some(value) = self.model.constants.get(&constant_name).copied() {
                    self.load_constant(value, width);
                } else {
                    let binding = self.binding(base)?;
                    let field = self.model.field(&binding.ty, field)?.clone();
                    let source_width = self.model.type_width(&field.ty)?;
                    let storage = self.binding_storage(&binding, "load aggregate field")?;
                    self.copy(
                        Storage {
                            address: storage.address + field.offset,
                            size: field.size,
                        },
                        self.r0,
                        u32::from(source_width),
                    );
                    self.extend_result(source_width, width, type_is_signed(&field.ty));
                }
            }
            Expr::Access(path) => {
                let (ty, _) = self.emit_access_address(path)?;
                let source_width = self.model.type_width(&ty)?;
                self.load_indirect(source_width);
                self.extend_result(source_width, width, false);
            }
            Expr::Deref(pointer) => {
                self.emit_expr(pointer, &Type::Ptr(Box::new(expected.clone())))?;
                self.copy_result_to_zp();
                self.load_indirect(width);
            }
            Expr::BankedPointer { pointer, .. } => self.emit_expr(pointer, expected)?,
            Expr::Call { path, args } => self.emit_call(path, args, expected)?,
            Expr::Unary { op, expr } => {
                self.emit_expr(expr, expected)?;
                self.emit_unary(*op, width);
            }
            Expr::Binary { left, op, right } => {
                if matches!(op, BinaryOp::And | BinaryOp::Or) {
                    self.emit_short_circuit(left, *op, right)?;
                    self.extend_result(1, width, false);
                    return Ok(());
                }
                let operand_ty = if is_comparison(*op) || matches!(op, BinaryOp::And | BinaryOp::Or)
                {
                    self.expr_type(left)
                        .or_else(|_| self.expr_type(right))
                        .unwrap_or(expected.clone())
                } else {
                    expected.clone()
                };
                let operand_width = self.model.type_width(&operand_ty)?;
                if matches!(op, BinaryOp::Shl | BinaryOp::Shr)
                    && let Some(count) = self.constant_shift_count(right)
                {
                    self.emit_expr(left, &operand_ty)?;
                    self.constant_shift(
                        operand_width,
                        *op == BinaryOp::Shr,
                        type_is_signed(&operand_ty),
                        count,
                    );
                    return Ok(());
                }
                self.emit_expr(left, &operand_ty)?;
                let left_storage = self.model.allocate(u32::from(operand_width))?;
                self.copy(self.r0, left_storage, u32::from(operand_width));
                self.emit_expr(right, &operand_ty)?;
                self.copy(self.r0, self.r1, u32::from(operand_width));
                self.copy(left_storage, self.r0, u32::from(operand_width));
                if matches!(op, BinaryOp::Add | BinaryOp::Sub)
                    && let Type::Ptr(inner) = self.model.resolved_type(&operand_ty)?
                {
                    self.scale_storage(self.r1, operand_width, self.model.type_size(&inner)?);
                }
                self.emit_binary_op(*op, operand_width, type_is_signed(&operand_ty))?;
                if is_comparison(*op) || matches!(op, BinaryOp::And | BinaryOp::Or) {
                    self.extend_result(1, width, false);
                }
            }
            Expr::Cast { ty, expr } => {
                let source_ty = self.expr_type(expr).unwrap_or_else(|_| ty.clone());
                let source_width = self.model.type_width(&source_ty)?;
                self.emit_expr(expr, &source_ty)?;
                self.extend_result(source_width, width, type_is_signed(&source_ty));
            }
            Expr::Array(_) | Expr::StructInit { .. } => {
                return Err(Diagnostic::new("aggregate value requires storage context"));
            }
        }
        Ok(())
    }

    fn live_storage_segments(
        &self,
        live: Storage,
        args: &[Expr],
        protected: &[Storage],
    ) -> Vec<Storage> {
        let mut excluded = args
            .iter()
            .filter_map(|arg| match arg {
                // The callee can mutate this storage through its pointer parameter.
                // Restoring a pre-call snapshot would discard that mutation.
                Expr::AddressOf(name) => self.binding(name).ok().and_then(|binding| match binding
                    .location
                {
                    BindingLocation::Storage(storage) => Some(storage),
                    BindingLocation::Register(_) => None,
                }),
                _ => None,
            })
            .filter_map(|storage| {
                let start = storage.address.max(live.address);
                let end = storage
                    .address
                    .saturating_add(storage.size)
                    .min(live.address.saturating_add(live.size));
                (start < end).then_some((start, end))
            })
            .collect::<Vec<_>>();
        excluded.extend(protected.iter().copied().filter_map(|storage| {
            let start = storage.address.max(live.address);
            let end = storage
                .address
                .saturating_add(storage.size)
                .min(live.address.saturating_add(live.size));
            (start < end).then_some((start, end))
        }));
        excluded.sort_unstable();

        let mut saved = Vec::new();
        let mut cursor = live.address;
        for (start, end) in excluded {
            if start > cursor {
                saved.push(Storage {
                    address: cursor,
                    size: start - cursor,
                });
            }
            cursor = cursor.max(end);
        }
        let live_end = live.address.saturating_add(live.size);
        if cursor < live_end {
            saved.push(Storage {
                address: cursor,
                size: live_end - cursor,
            });
        }
        saved
    }

    fn emit_two_result_call(
        &mut self,
        value: &Expr,
        first_ty: &Type,
        second_ty: &Type,
        second_destination: Storage,
    ) -> Result<(), Diagnostic> {
        let Expr::Call { path, args } = value else {
            return Err(Diagnostic::new(
                "two-result bindings require a direct two-result call",
            ));
        };
        let name = path.join(".");
        if CATALOG.lookup(&name).is_some() {
            return self.emit_intrinsic_two_result_call(
                &name,
                args,
                first_ty,
                second_ty,
                second_destination,
            );
        }
        let resolved_name = resolve_called_function(path, &self.model)
            .ok_or_else(|| Diagnostic::new(format!("unknown function `{name}`")))?;
        let signature = self.model.functions[&resolved_name].clone();
        let Some(signature_second) = signature.second_return_type.as_ref() else {
            return Err(Diagnostic::new(format!(
                "function `{name}` does not return two values"
            )));
        };
        let Some(signature_first) = signature.return_type.as_ref() else {
            return Err(Diagnostic::new(format!(
                "two-result function `{name}` has no first return type"
            )));
        };
        if self.model.resolved_type(signature_first)? != self.model.resolved_type(first_ty)? {
            return Err(Diagnostic::new(format!(
                "first result of `{name}` does not match its binding"
            )));
        }
        if self.model.resolved_type(signature_second)? != self.model.resolved_type(second_ty)? {
            return Err(Diagnostic::new(format!(
                "second result of `{name}` does not match its binding"
            )));
        }
        if signature.params.len() != args.len() {
            return Err(Diagnostic::new(format!(
                "function `{name}` expects {} arguments, got {}",
                signature.params.len(),
                args.len()
            )));
        }
        let second_width = self.model.type_width(signature_second)?;
        if second_destination.size < u32::from(second_width) {
            return Err(Diagnostic::new(format!(
                "second result destination for `{name}` is too small"
            )));
        }
        let mut evaluated_args = Vec::with_capacity(args.len());
        for (index, arg) in args.iter().enumerate() {
            let ty = &signature.params[index];
            let storage = self.model.allocate(self.model.type_size(ty)?)?;
            self.emit_initializer(storage, ty, arg)?;
            evaluated_args.push(storage);
        }
        for (storage, argument_slot) in evaluated_args.into_iter().zip(&signature.argument_slots) {
            self.copy(storage, *argument_slot, storage.size);
        }
        let saved = self
            .function_ram_bases
            .last()
            .map(|base| Storage {
                address: *base,
                size: self.model.next_ram_address() - *base,
            })
            .map(|live| self.live_storage_segments(live, args, &[second_destination]))
            .unwrap_or_default();
        for storage in &saved {
            for offset in 0..storage.size {
                self.lda(storage.address + offset);
                self.line("    pha");
            }
        }
        let argument_registers = self.argument_registers(&signature.params)?;
        for (index, (ty, slot)) in signature
            .params
            .iter()
            .zip(&signature.argument_slots)
            .enumerate()
        {
            if let Some(register) = argument_registers[index] {
                for offset in 0..self.model.type_size(ty)? {
                    self.line(&format!(
                        "    lds r{}, {:04X}h",
                        register + offset as u8,
                        slot.address + offset
                    ));
                }
            }
        }
        self.line(&format!(
            "    ldi r26, {:02X}h",
            second_destination.address & 0xFF
        ));
        self.line(&format!(
            "    ldi r27, {:02X}h",
            (second_destination.address >> 8) & 0xFF
        ));
        self.line(&format!("    jsr {}", function_label(&resolved_name)));
        let return_storage = self
            .model
            .allocate(self.model.type_size(signature_first)?)?;
        self.copy(self.r0, return_storage, return_storage.size);
        for storage in saved.iter().rev() {
            for offset in (0..storage.size).rev() {
                self.line("    pla");
                self.sta(storage.address + offset);
            }
        }
        self.copy(return_storage, self.r0, return_storage.size);
        self.extend_result(
            self.model.type_width(signature_first)?,
            self.model.type_width(first_ty)?,
            type_is_signed(signature_first),
        );
        Ok(())
    }

    fn emit_return_two(&mut self, first: &Expr, second: &Expr) -> Result<(), Diagnostic> {
        let Some(first_type) = self.return_types.last().and_then(Clone::clone) else {
            return Err(Diagnostic::new(
                "function cannot return two values without a first return type",
            ));
        };
        let Some(second_type) = self.second_return_types.last().and_then(Clone::clone) else {
            return Err(Diagnostic::new("function cannot return two values"));
        };
        let Some(pointer) = self.second_return_pointers.last().copied().flatten() else {
            return Err(Diagnostic::new(
                "two-result function has no caller-provided return slot",
            ));
        };
        let first_value = self.model.allocate(self.model.type_size(&first_type)?)?;
        let second_width = self.model.type_width(&second_type)?;
        self.emit_expr(first, &first_type)?;
        self.copy(self.r0, first_value, first_value.size);
        self.emit_expr(second, &second_type)?;
        self.set_zp_from_storage(POINTER_ZP, pointer);
        self.copy_storage_to_indirect(self.r0, u32::from(second_width));
        self.copy(first_value, self.r0, first_value.size);
        let label = self
            .return_labels
            .last()
            .expect("function return label")
            .clone();
        self.line(&format!("    jmp {label}"));
        Ok(())
    }

    fn emit_call(
        &mut self,
        path: &[String],
        args: &[Expr],
        expected: &Type,
    ) -> Result<(), Diagnostic> {
        let name = path.join(".");
        if CATALOG.lookup(&name).is_some() {
            return self.emit_intrinsic_call(&name, args, expected);
        }
        match name.as_str() {
            "mem.peek8" | "ezra.mem.peek8" => {
                self.emit_expr(&args[0], &Type::Ptr(Box::new(Type::Named("u8".to_owned()))))?;
                self.copy_result_to_zp();
                self.load_indirect(1);
                return Ok(());
            }
            "mem.poke8" | "ezra.mem.poke8" => {
                self.emit_expr(&args[0], &Type::Ptr(Box::new(Type::Named("u8".to_owned()))))?;
                let destination = self.model.allocate(2)?;
                self.copy(self.r0, destination, 2);
                self.emit_expr(&args[1], &Type::Named("u8".to_owned()))?;
                self.set_zp_from_storage(POINTER_ZP, destination);
                self.lda(self.r0.address);
                self.line("    ldy #$00");
                self.line(&format!("    sta (${:02X}),y", POINTER_ZP));
                return Ok(());
            }
            "mem.memcpy" | "ezra.mem.memcpy" => {
                self.emit_memcpy(args)?;
                return Ok(());
            }
            "mem.memset" | "ezra.mem.memset" => {
                self.emit_memset(args)?;
                return Ok(());
            }
            _ => {}
        }
        let (signature, direct_target, indirect_target) =
            if let Some(resolved_name) = resolve_called_function(path, &self.model) {
                (
                    self.model.functions[&resolved_name].clone(),
                    Some(resolved_name),
                    None,
                )
            } else {
                if path.len() != 1 {
                    return Err(Diagnostic::new(format!("unknown function `{name}`")));
                }
                let binding = self.binding(&path[0])?;
                let resolved_binding_type = self.model.resolved_type(&binding.ty)?;
                let Type::Ptr(inner) = &resolved_binding_type else {
                    return Err(Diagnostic::new(format!(
                        "function pointer call requires `ptr<fn(...)>`, got `{name}`"
                    )));
                };
                let Type::Function {
                    params,
                    return_type,
                } = inner.as_ref()
                else {
                    return Err(Diagnostic::new(format!(
                        "function pointer call requires `ptr<fn(...)>`, got `{name}`"
                    )));
                };
                let argument_slots = params
                    .iter()
                    .map(|param| self.model.allocate_type(param))
                    .collect::<Result<Vec<_>, _>>()?;
                let pointer_storage = self.model.allocate(2)?;
                (
                    crate::tbir::model::FunctionSignature {
                        params: params.clone(),
                        return_type: return_type.clone().map(|ty| *ty),
                        second_return_type: None,
                        argument_slots,
                    },
                    None,
                    Some((binding, pointer_storage)),
                )
            };
        if signature.second_return_type.is_some() {
            return Err(Diagnostic::new(format!(
                "two-result function `{name}` requires a two-destination call"
            )));
        }
        if signature.params.len() != args.len() {
            return Err(Diagnostic::new(format!(
                "function `{name}` expects {} arguments, got {}",
                signature.params.len(),
                args.len()
            )));
        }
        let mut evaluated_args = Vec::with_capacity(args.len());
        for (index, arg) in args.iter().enumerate() {
            let ty = &signature.params[index];
            let storage = self.model.allocate(self.model.type_size(ty)?)?;
            self.emit_initializer(storage, ty, arg)?;
            evaluated_args.push(storage);
        }
        if let Some((binding, pointer_storage)) = &indirect_target {
            self.load_binding_result(binding)?;
            self.copy(self.r0, *pointer_storage, 2);
        }
        for (storage, argument_slot) in evaluated_args.into_iter().zip(&signature.argument_slots) {
            self.copy(storage, *argument_slot, storage.size);
        }
        let protected = indirect_target
            .as_ref()
            .map(|(_, storage)| vec![*storage])
            .unwrap_or_default();
        let saved = self
            .function_ram_bases
            .last()
            .map(|base| Storage {
                address: *base,
                size: self.model.next_ram_address() - *base,
            })
            .map(|live| self.live_storage_segments(live, args, &protected))
            .unwrap_or_default();
        for storage in &saved {
            for offset in 0..storage.size {
                self.lda(storage.address + offset);
                self.line("    pha");
            }
        }
        let argument_registers = self.argument_registers(&signature.params)?;
        for (index, (ty, slot)) in signature
            .params
            .iter()
            .zip(&signature.argument_slots)
            .enumerate()
        {
            if let Some(register) = argument_registers[index] {
                for offset in 0..self.model.type_size(ty)? {
                    self.line(&format!(
                        "    lds r{}, {:04X}h",
                        register + offset as u8,
                        slot.address + offset
                    ));
                }
            }
        }
        if let Some(resolved_name) = direct_target {
            self.line(&format!("    jsr {}", function_label(&resolved_name)));
        } else if let Some((_, pointer_storage)) = indirect_target {
            self.line(&format!("    lds r30, {:04X}h", pointer_storage.address));
            self.line(&format!(
                "    lds r31, {:04X}h",
                pointer_storage.address + 1
            ));
            self.line("    icall");
        }
        if let Some(ty) = &signature.return_type {
            for offset in 0..self.model.type_size(ty)? {
                self.line(&format!(
                    "    sts {:04X}h, r{}",
                    self.r0.address + offset,
                    24 + offset
                ));
            }
        }
        let return_storage = signature
            .return_type
            .as_ref()
            .map(|ty| self.model.type_size(ty))
            .transpose()?
            .map(|size| self.model.allocate(size))
            .transpose()?;
        if let Some(return_storage) = return_storage {
            self.copy(self.r0, return_storage, return_storage.size);
        }
        for storage in saved.iter().rev() {
            for offset in (0..storage.size).rev() {
                self.line("    pla");
                self.sta(storage.address + offset);
            }
        }
        if let Some(return_storage) = return_storage {
            self.copy(return_storage, self.r0, return_storage.size);
        }
        if let Some(return_type) = &signature.return_type {
            let return_width = self.model.type_width(return_type)?;
            self.extend_result(return_width, self.model.type_width(expected)?, false);
        } else {
            self.zero(self.r0);
        }
        Ok(())
    }

    fn resolve_intrinsic(
        &self,
        name: &str,
        args: &[Expr],
    ) -> Result<crate::intrinsics::IntrinsicResolution, Diagnostic> {
        let argument_types = args
            .iter()
            .map(|arg| self.model.resolved_type(&self.expr_type(arg)?))
            .collect::<Result<Vec<_>, _>>()?;
        let constants = args
            .iter()
            .map(|arg| self.model.const_value(arg).ok())
            .collect::<Vec<_>>();
        CATALOG
            .validate_types_with_constants(name, &argument_types, &constants)
            .map_err(|error| Diagnostic::new(error.to_string()))
    }

    fn intrinsic_arguments(
        &mut self,
        args: &[Expr],
        resolution: &crate::intrinsics::IntrinsicResolution,
    ) -> Result<Vec<Storage>, Diagnostic> {
        resolution
            .argument_types
            .iter()
            .zip(args)
            .map(|(ty, arg)| {
                let storage = self.model.allocate(self.model.type_size(ty)?)?;
                self.emit_initializer(storage, ty, arg)?;
                Ok(storage)
            })
            .collect()
    }

    fn emit_intrinsic_call(
        &mut self,
        name: &str,
        args: &[Expr],
        expected: &Type,
    ) -> Result<(), Diagnostic> {
        let resolution = self.resolve_intrinsic(name, args)?;
        if resolution.result_types.len() == 2 {
            return Err(Diagnostic::new(format!(
                "two-result intrinsic `{name}` requires a two-destination call"
            )));
        }
        let values = self.intrinsic_arguments(args, &resolution)?;
        let constants = args
            .iter()
            .map(|arg| self.model.const_value(arg).ok())
            .collect::<Vec<_>>();
        if let Some(result) = resolution.result_types.first()
            && self.model.resolved_type(result)? != self.model.resolved_type(expected)?
        {
            return Err(Diagnostic::new(format!(
                "result of intrinsic `{name}` does not match the expected type"
            )));
        }
        self.lower_intrinsic(
            resolution.descriptor.operation,
            &resolution.argument_types,
            &values,
            &constants,
            Some(expected),
            None,
        )
    }

    fn emit_intrinsic_two_result_call(
        &mut self,
        name: &str,
        args: &[Expr],
        first_ty: &Type,
        second_ty: &Type,
        second_destination: Storage,
    ) -> Result<(), Diagnostic> {
        let resolution = self.resolve_intrinsic(name, args)?;
        if resolution.result_types.len() != 2
            || self.model.resolved_type(&resolution.result_types[0])?
                != self.model.resolved_type(first_ty)?
            || self.model.resolved_type(&resolution.result_types[1])?
                != self.model.resolved_type(second_ty)?
        {
            return Err(Diagnostic::new(format!(
                "result types of intrinsic `{name}` do not match the two-result bindings"
            )));
        }
        let second_width = self.model.type_width(second_ty)?;
        if second_destination.size < u32::from(second_width) {
            return Err(Diagnostic::new(format!(
                "second result destination for `{name}` is too small"
            )));
        }
        let values = self.intrinsic_arguments(args, &resolution)?;
        let constants = args
            .iter()
            .map(|arg| self.model.const_value(arg).ok())
            .collect::<Vec<_>>();
        self.lower_intrinsic(
            resolution.descriptor.operation,
            &resolution.argument_types,
            &values,
            &constants,
            Some(first_ty),
            Some(second_destination),
        )
    }

    fn lower_intrinsic(
        &mut self,
        operation: IntrinsicOperation,
        argument_types: &[Type],
        values: &[Storage],
        constants: &[Option<i64>],
        _result_type: Option<&Type>,
        second_destination: Option<Storage>,
    ) -> Result<(), Diagnostic> {
        match operation {
            IntrinsicOperation::Bits(operation) => {
                self.lower_bits_intrinsic(operation, argument_types, values, constants)
            }
            IntrinsicOperation::Int(operation) => {
                self.lower_int_intrinsic(operation, argument_types, values, second_destination)
            }
            IntrinsicOperation::Mem(operation) => {
                self.lower_mem_intrinsic(operation, values, second_destination)
            }
        }
    }

    fn lower_bits_intrinsic(
        &mut self,
        operation: BitsIntrinsic,
        argument_types: &[Type],
        values: &[Storage],
        constants: &[Option<i64>],
    ) -> Result<(), Diagnostic> {
        let width = self.model.type_width(&argument_types[0])?;
        let size = u32::from(width);
        match operation {
            BitsIntrinsic::Test
            | BitsIntrinsic::Set
            | BitsIntrinsic::Clear
            | BitsIntrinsic::Toggle => {
                let bit =
                    usize::try_from(constants[1].ok_or_else(|| {
                        Diagnostic::new("bit index must be a compile-time constant")
                    })?)
                    .map_err(|_| Diagnostic::new("bit index must be non-negative"))?;
                let byte = (bit / 8) as u32;
                let mask = 1_u8 << (bit % 8);
                self.copy(values[0], self.r0, size);
                self.lda(self.r0.address + byte);
                match operation {
                    BitsIntrinsic::Test => {
                        self.line(&format!("    and #${mask:02X}"));
                        let set = self.next_label("intrinsic_bit_set");
                        let done = self.next_label("intrinsic_bit_done");
                        self.branch_long("bne", &set);
                        self.load_constant(0, 1);
                        self.line(&format!("    jmp {done}"));
                        self.line(&format!("{set}:"));
                        self.load_constant(1, 1);
                        self.line(&format!("{done}:"));
                    }
                    BitsIntrinsic::Set => {
                        self.line(&format!("    ora #${mask:02X}"));
                        self.sta(self.r0.address + byte);
                    }
                    BitsIntrinsic::Clear => {
                        self.line(&format!("    and #${:02X}", !mask));
                        self.sta(self.r0.address + byte);
                    }
                    BitsIntrinsic::Toggle => {
                        self.line(&format!("    eor #${mask:02X}"));
                        self.sta(self.r0.address + byte);
                    }
                    _ => unreachable!(),
                }
            }
            BitsIntrinsic::Extract => {
                let offset = intrinsic_constant(constants, 1)?;
                let bits = intrinsic_constant(constants, 2)?;
                self.copy(values[0], self.r0, size);
                self.constant_shift(width, true, false, offset as u8);
                self.intrinsic_mask(self.r0, size, intrinsic_mask(bits));
            }
            BitsIntrinsic::Insert => {
                let offset = intrinsic_constant(constants, 2)?;
                let bits = intrinsic_constant(constants, 3)?;
                let mask = intrinsic_mask(bits).checked_shl(offset).unwrap_or(0);
                self.copy(values[0], self.r2, size);
                self.copy(values[1], self.r0, size);
                self.constant_shift(width, false, false, offset as u8);
                self.copy(self.r0, self.r1, size);
                self.copy(self.r2, self.r0, size);
                self.intrinsic_mask(self.r1, size, mask);
                self.intrinsic_mask(self.r0, size, !mask);
                self.intrinsic_or(self.r0, self.r1, width);
            }
            BitsIntrinsic::ByteSwap => {
                self.copy(values[0], self.r0, size);
                for offset in 0..size / 2 {
                    let other = size - offset - 1;
                    self.lda(self.r0.address + offset);
                    self.line(&format!("    pha"));
                    self.lda(self.r0.address + other);
                    self.sta(self.r0.address + offset);
                    self.line("    pla");
                    self.sta(self.r0.address + other);
                }
            }
            BitsIntrinsic::Reverse => self.intrinsic_reverse(values[0], width as u8),
            BitsIntrinsic::CountOnes => self.intrinsic_count_bits(values[0], width as u8, false),
            BitsIntrinsic::LeadingZeros => self.intrinsic_count_bits(values[0], width as u8, true),
            BitsIntrinsic::TrailingZeros => {
                self.intrinsic_count_bits(values[0], width as u8, false)
            }
            BitsIntrinsic::RotateLeft | BitsIntrinsic::RotateRight => {
                self.intrinsic_rotate(operation, values[0], values[1], width as u8)?
            }
        }
        Ok(())
    }

    fn lower_int_intrinsic(
        &mut self,
        operation: IntIntrinsic,
        argument_types: &[Type],
        values: &[Storage],
        second_destination: Option<Storage>,
    ) -> Result<(), Diagnostic> {
        let width = self.model.type_width(&argument_types[0])? as u8;
        let signed = type_is_signed(&argument_types[0]);
        match operation {
            IntIntrinsic::WideningMul => {
                let right_width = self.model.type_width(&argument_types[1])? as u8;
                let product =
                    self.intrinsic_full_product(values[0], values[1], width, right_width, signed)?;
                self.copy(product, self.r0, u32::from(width + right_width));
            }
            IntIntrinsic::MulHigh => {
                let product =
                    self.intrinsic_full_product(values[0], values[1], width, width, signed)?;
                self.copy(
                    Storage {
                        address: product.address + u32::from(width),
                        size: u32::from(width),
                    },
                    self.r0,
                    u32::from(width),
                );
            }
            IntIntrinsic::SaturatingAdd | IntIntrinsic::SaturatingSub => {
                self.copy(values[0], self.r0, u32::from(width));
                self.copy(values[1], self.r1, u32::from(width));
                if operation == IntIntrinsic::SaturatingAdd {
                    self.add(width);
                } else {
                    self.sub(width);
                }
                let overflow = self.next_label("intrinsic_sat_overflow");
                let done = self.next_label("intrinsic_sat_done");
                if !signed {
                    self.native_line(&format!("    brcs {overflow}"));
                    self.line(&format!("    jmp {done}"));
                    self.line(&format!("{overflow}:"));
                    self.load_constant(
                        if operation == IntIntrinsic::SaturatingAdd {
                            (1_i64 << (u32::from(width) * 8)) - 1
                        } else {
                            0
                        },
                        width,
                    );
                } else {
                    let lhs_negative = self.next_label("intrinsic_lhs_negative");
                    let no_overflow = self.next_label("intrinsic_no_overflow");
                    self.lda(values[0].address + u32::from(width - 1));
                    self.branch_long("bmi", &lhs_negative);
                    self.lda(values[1].address + u32::from(width - 1));
                    self.branch_long(
                        if operation == IntIntrinsic::SaturatingAdd {
                            "bmi"
                        } else {
                            "bpl"
                        },
                        &no_overflow,
                    );
                    self.lda(self.r0.address + u32::from(width - 1));
                    self.branch_long("bmi", &no_overflow);
                    self.load_constant((1_i64 << (u32::from(width) * 8 - 1)) - 1, width);
                    self.line(&format!("    jmp {done}"));
                    self.line(&format!("{lhs_negative}:"));
                    self.lda(values[1].address + u32::from(width - 1));
                    self.branch_long(
                        if operation == IntIntrinsic::SaturatingAdd {
                            "bpl"
                        } else {
                            "bmi"
                        },
                        &no_overflow,
                    );
                    self.lda(self.r0.address + u32::from(width - 1));
                    self.branch_long("bmi", &no_overflow);
                    self.load_constant(-(1_i64 << (u32::from(width) * 8 - 1)), width);
                    self.line(&format!("{no_overflow}:"));
                }
                self.line(&format!("{done}:"));
            }
            IntIntrinsic::Divmod => {
                let second = second_destination
                    .ok_or_else(|| Diagnostic::new("divmod requires two destinations"))?;
                let quotient = self.model.allocate(u32::from(width))?;
                self.copy(values[0], self.r0, u32::from(width));
                self.copy(values[1], self.r1, u32::from(width));
                self.divide(width, false, signed);
                self.copy(self.r0, quotient, u32::from(width));
                self.copy(values[0], self.r0, u32::from(width));
                self.copy(values[1], self.r1, u32::from(width));
                self.divide(width, true, signed);
                self.copy(self.r0, second, u32::from(width));
                self.copy(quotient, self.r0, u32::from(width));
            }
            IntIntrinsic::AddCarry | IntIntrinsic::SubBorrow => {
                let second = second_destination.ok_or_else(|| {
                    Diagnostic::new("paired integer intrinsic requires two destinations")
                })?;
                self.copy(values[0], self.r0, u32::from(width));
                self.copy(values[1], self.r1, u32::from(width));
                let with_flag = self.next_label("intrinsic_with_flag");
                let done = self.next_label("intrinsic_carry_done");
                self.jump_if_nonzero(values[2].address, &with_flag);
                self.native_line("    clc");
                self.intrinsic_add_sub_with_carry(width, operation == IntIntrinsic::AddCarry);
                self.line(&format!("    jmp {done}"));
                self.line(&format!("{with_flag}:"));
                self.native_line("    sec");
                self.intrinsic_add_sub_with_carry(width, operation == IntIntrinsic::AddCarry);
                self.line(&format!("{done}:"));
                let no_carry = self.next_label("intrinsic_no_carry");
                let carry = self.next_label("intrinsic_carry");
                self.native_line(&format!("    brcc {no_carry}"));
                self.line(&format!("    jmp {carry}"));
                self.line(&format!("{no_carry}:"));
                self.load_constant_into(second, 0, 1);
                let result_done = self.next_label("intrinsic_result_done");
                self.line(&format!("    jmp {result_done}"));
                self.line(&format!("{carry}:"));
                self.load_constant_into(second, 1, 1);
                self.line(&format!("{result_done}:"));
            }
            IntIntrinsic::FullMul => {
                let second = second_destination
                    .ok_or_else(|| Diagnostic::new("full_mul requires two destinations"))?;
                let product =
                    self.intrinsic_full_product(values[0], values[1], width, width, signed)?;
                self.copy(product, self.r0, u32::from(width));
                self.copy(
                    Storage {
                        address: product.address + u32::from(width),
                        size: u32::from(width),
                    },
                    second,
                    u32::from(width),
                );
            }
        }
        Ok(())
    }

    fn lower_mem_intrinsic(
        &mut self,
        operation: MemIntrinsic,
        values: &[Storage],
        second_destination: Option<Storage>,
    ) -> Result<(), Diagnostic> {
        match operation {
            MemIntrinsic::Peek8 => {
                self.set_zp_from_storage(POINTER_ZP, values[0]);
                self.load_indirect(1);
            }
            MemIntrinsic::Poke8 => {
                self.set_zp_from_storage(POINTER_ZP, values[0]);
                self.lda(values[1].address);
                self.line("    ldy #$00");
                self.line(&format!("    sta (${:02X}),y", POINTER_ZP));
            }
            MemIntrinsic::LoadLe16
            | MemIntrinsic::LoadBe16
            | MemIntrinsic::LoadLe24
            | MemIntrinsic::LoadBe24 => {
                let width = match operation {
                    MemIntrinsic::LoadLe16 | MemIntrinsic::LoadBe16 => 2,
                    _ => 3,
                };
                let raw = self.model.allocate(width)?;
                self.set_zp_from_storage(POINTER_ZP, values[0]);
                for offset in 0..width {
                    self.native_line(&format!(
                        "    ld r16, z+\n    sts {:04X}h, r16",
                        raw.address + offset
                    ));
                }
                for offset in 0..width {
                    let source =
                        if matches!(operation, MemIntrinsic::LoadLe16 | MemIntrinsic::LoadLe24) {
                            offset
                        } else {
                            width - offset - 1
                        };
                    self.lda(raw.address + source);
                    self.sta(self.r0.address + offset);
                }
            }
            MemIntrinsic::StoreLe16
            | MemIntrinsic::StoreBe16
            | MemIntrinsic::StoreLe24
            | MemIntrinsic::StoreBe24 => {
                let width = match operation {
                    MemIntrinsic::StoreLe16 | MemIntrinsic::StoreBe16 => 2,
                    _ => 3,
                };
                for offset in 0..width {
                    let source =
                        if matches!(operation, MemIntrinsic::StoreLe16 | MemIntrinsic::StoreLe24) {
                            offset
                        } else {
                            width - offset - 1
                        };
                    self.set_zp_from_storage(POINTER_ZP, values[0]);
                    if offset != 0 {
                        self.native_line(&format!("    adiw r30, {}", offset));
                    }
                    self.lda(values[1].address + source);
                    self.native_line("    st z, r16");
                }
                self.zero(self.r0);
            }
            MemIntrinsic::CopyNonoverlapping | MemIntrinsic::Move | MemIntrinsic::Fill => {
                self.intrinsic_memory_range(operation, values)?;
                self.zero(self.r0);
            }
            MemIntrinsic::FindByte => {
                let second = second_destination
                    .ok_or_else(|| Diagnostic::new("find_byte requires two destinations"))?;
                self.intrinsic_find_byte(values, second);
            }
            MemIntrinsic::Compare => self.intrinsic_compare(values),
        }
        Ok(())
    }

    fn intrinsic_mask(&mut self, storage: Storage, width: u32, mask: u32) {
        for offset in 0..width {
            self.lda(storage.address + offset);
            self.line(&format!("    and #${:02X}", (mask >> (offset * 8)) & 0xff));
            self.sta(storage.address + offset);
        }
    }

    fn intrinsic_or(&mut self, target: Storage, source: Storage, width: u8) {
        for offset in 0..u32::from(width) {
            self.lda(target.address + offset);
            self.line(&format!("    ora ${:04X}", source.address + offset));
            self.sta(target.address + offset);
        }
    }

    fn intrinsic_reverse(&mut self, source: Storage, width: u8) {
        let input = self
            .model
            .allocate(u32::from(width))
            .expect("reverse input");
        let output = self
            .model
            .allocate(u32::from(width))
            .expect("reverse output");
        self.copy(source, input, u32::from(width));
        self.zero(output);
        for _ in 0..u32::from(width) * 8 {
            self.copy(output, self.r0, u32::from(width));
            self.constant_shift(width, false, false, 1);
            self.copy(self.r0, output, u32::from(width));
            self.lda(input.address);
            self.line("    and #$01");
            let no_bit = self.next_label("reverse_no_bit");
            self.branch_long("beq", &no_bit);
            self.lda(output.address);
            self.line("    ora #$01");
            self.sta(output.address);
            self.line(&format!("{no_bit}:"));
            self.copy(input, self.r0, u32::from(width));
            self.constant_shift(width, true, false, 1);
            self.copy(self.r0, input, u32::from(width));
        }
        self.copy(output, self.r0, u32::from(width));
    }

    fn intrinsic_count_bits(&mut self, source: Storage, width: u8, leading: bool) {
        let input = self.model.allocate(u32::from(width)).expect("count input");
        self.copy(source, input, u32::from(width));
        self.zero(self.r0);
        let done = self.next_label("count_bits_done");
        for _ in 0..u32::from(width) * 8 {
            let offset = if leading { u32::from(width - 1) } else { 0 };
            self.lda(input.address + offset);
            self.line(if leading {
                "    and #$80"
            } else {
                "    and #$01"
            });
            if leading {
                self.branch_long("bne", &done);
            } else {
                let one = self.next_label("count_bit_one");
                self.branch_long("bne", &one);
                self.line(&format!("    jmp {done}"));
                self.line(&format!("{one}:"));
            }
            self.lda(self.r0.address);
            self.line("    inc r16");
            self.sta(self.r0.address);
            self.copy(input, self.r0, u32::from(width));
            self.constant_shift(width, leading, false, 1);
            self.copy(self.r0, input, u32::from(width));
        }
        self.line(&format!("{done}:"));
    }

    fn intrinsic_rotate(
        &mut self,
        operation: BitsIntrinsic,
        value: Storage,
        count: Storage,
        width: u8,
    ) -> Result<(), Diagnostic> {
        let remaining = self.model.allocate(count.size)?;
        self.copy(count, remaining, count.size);
        self.copy(value, self.r0, u32::from(width));
        let loop_label = self.next_label("rotate_loop");
        let done = self.next_label("rotate_done");
        self.line(&format!("{loop_label}:"));
        self.jump_storage_zero(remaining, count.size as u8, &done);
        self.constant_shift(width, operation == BitsIntrinsic::RotateRight, false, 1);
        let no_carry = self.next_label("rotate_no_carry");
        self.native_line(&format!("    brcc {no_carry}"));
        if operation == BitsIntrinsic::RotateRight {
            self.lda(self.r0.address + u32::from(width - 1));
            self.line("    ora #$80");
            self.sta(self.r0.address + u32::from(width - 1));
        } else {
            self.lda(self.r0.address);
            self.line("    ora #$01");
            self.sta(self.r0.address);
        }
        self.line(&format!("{no_carry}:"));
        self.decrement(remaining, count.size as u8);
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{done}:"));
        Ok(())
    }

    fn intrinsic_full_product(
        &mut self,
        left: Storage,
        right: Storage,
        left_width: u8,
        right_width: u8,
        signed: bool,
    ) -> Result<Storage, Diagnostic> {
        let product_width = left_width + right_width;
        if left_width == 1 && right_width == 1 {
            let product = self.model.allocate(2)?;
            self.lda(left.address);
            self.native_line(&format!(
                "    lds r18, {:04X}h\n    {} r16, r18\n    sts {:04X}h, r0\n    sts {:04X}h, r1\n    clr r1",
                right.address,
                if signed { "muls" } else { "mul" },
                product.address,
                product.address + 1
            ));
            return Ok(product);
        }
        let product = self.model.allocate(u32::from(product_width))?;
        let multiplicand = self.model.allocate(u32::from(product_width))?;
        let multiplier = self.model.allocate(u32::from(right_width))?;
        let negative = self.model.allocate(1)?;
        self.zero(product);
        self.zero(multiplicand);
        self.copy(left, multiplicand, u32::from(left_width));
        self.copy(right, multiplier, u32::from(right_width));
        self.zero(negative);
        if signed {
            self.normalize_signed_operand(multiplicand, left_width, negative, false);
            self.normalize_signed_operand(multiplier, right_width, negative, true);
        }
        for _ in 0..u32::from(right_width) * 8 {
            self.lda(multiplier.address);
            self.line("    and #$01");
            let no_add = self.next_label("multiply_no_add");
            self.branch_long("beq", &no_add);
            self.copy(product, self.r0, u32::from(product_width));
            self.copy(multiplicand, self.r1, u32::from(product_width));
            self.add(product_width);
            self.copy(self.r0, product, u32::from(product_width));
            self.line(&format!("{no_add}:"));
            self.copy(multiplicand, self.r0, u32::from(product_width));
            self.constant_shift(product_width, false, false, 1);
            self.copy(self.r0, multiplicand, u32::from(product_width));
            self.copy(multiplier, self.r0, u32::from(right_width));
            self.constant_shift(right_width, true, false, 1);
            self.copy(self.r0, multiplier, u32::from(right_width));
        }
        if signed {
            self.negate_if_flag(product, product_width, negative);
        }
        Ok(product)
    }

    fn intrinsic_add_sub_with_carry(&mut self, width: u8, add: bool) {
        for offset in 0..u32::from(width) {
            self.lda(self.r0.address + offset);
            self.line(&format!(
                "    {} ${:04X}",
                if add { "adc" } else { "sbc" },
                self.r1.address + offset
            ));
            self.sta(self.r0.address + offset);
        }
    }

    fn intrinsic_memory_range(
        &mut self,
        operation: MemIntrinsic,
        values: &[Storage],
    ) -> Result<(), Diagnostic> {
        let length = values[2];
        if operation == MemIntrinsic::Fill {
            self.set_zp_from_storage(POINTER_ZP, values[0]);
            self.native_line("    lds r26, 0100h\n    lds r27, 0101h\n    lds r18, 0100h");
            let manual = self.next_label("fill_loop");
            let done = self.next_label("fill_done");
            self.line(&format!("{manual}:"));
            self.jump_storage_zero(length, 3, &done);
            self.lda(values[1].address);
            self.native_line("    mov r18, r16\n    st x+, r18");
            self.decrement(length, 3);
            self.line(&format!("    jmp {manual}"));
            self.line(&format!("{done}:"));
            return Ok(());
        }
        self.set_zp_from_storage(POINTER_ZP, values[1]);
        self.set_zp_from_storage(POINTER_ZP + 2, values[0]);
        self.native_line(
            "    lds r30, 0100h\n    lds r31, 0101h\n    lds r26, 0102h\n    lds r27, 0103h",
        );
        if operation == MemIntrinsic::Move {
            let choose_forward = self.next_label("move_choose_forward");
            let backward = self.next_label("move_backward");
            let forward = self.next_label("move_forward");
            let done = self.next_label("move_done");
            self.native_line(&format!("    cp r26, r30\n    cpc r27, r31\n    brlo {choose_forward}\n    breq {choose_forward}\n    jmp {backward}\n{choose_forward}:\n    jmp {forward}"));
            self.line(&format!("{backward}:"));
            self.intrinsic_copy_backward_avr(length);
            self.line(&format!("    jmp {done}"));
            self.line(&format!("{forward}:"));
            self.set_zp_from_storage(POINTER_ZP, values[1]);
            self.set_zp_from_storage(POINTER_ZP + 2, values[0]);
            self.native_line(
                "    lds r30, 0100h\n    lds r31, 0101h\n    lds r26, 0102h\n    lds r27, 0103h",
            );
            self.intrinsic_copy_forward_avr(length);
            self.line(&format!("{done}:"));
        } else {
            self.intrinsic_copy_forward_avr(length);
        }
        Ok(())
    }

    fn intrinsic_copy_forward_avr(&mut self, length: Storage) {
        let loop_label = self.next_label("copy_forward_loop");
        let done = self.next_label("copy_forward_done");
        self.line(&format!("{loop_label}:"));
        self.jump_storage_zero(length, 3, &done);
        self.native_line("    ld r18, z+\n    st x+, r18");
        self.decrement(length, 3);
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{done}:"));
    }

    fn intrinsic_copy_backward_avr(&mut self, length: Storage) {
        self.native_line(&format!("    lds r18, {:04X}h\n    lds r19, {:04X}h\n    subi r18, 01h\n    sbci r19, 00h\n    add r30, r18\n    adc r31, r19\n    add r26, r18\n    adc r27, r19", length.address, length.address + 1));
        let loop_label = self.next_label("copy_backward_loop");
        let done = self.next_label("copy_backward_done");
        self.line(&format!("{loop_label}:"));
        self.jump_storage_zero(length, 3, &done);
        self.native_line(
            "    ld r18, z\n    st x, r18
    sbiw r30, 1
    sbiw r26, 1",
        );
        self.decrement(length, 3);
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{done}:"));
    }

    fn intrinsic_find_byte(&mut self, values: &[Storage], second: Storage) {
        self.set_zp_from_storage(POINTER_ZP, values[0]);
        self.native_line("    lds r30, 0100h\n    lds r31, 0101h");
        let length = values[1];
        let loop_label = self.next_label("find_byte_loop");
        let found = self.next_label("find_byte_found");
        let not_found = self.next_label("find_byte_not_found");
        let done = self.next_label("find_byte_done");
        self.line(&format!("{loop_label}:"));
        self.jump_storage_zero(length, 3, &not_found);
        self.native_line("    ld r18, z");
        self.lda(values[2].address);
        self.native_line("    cp r18, r16");
        self.native_line(&format!("    breq {found}"));
        self.native_line("    adiw r30, 1");
        self.decrement(length, 3);
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{found}:"));
        self.native_line(&format!(
            "    lds r16, 0100h\n    sts {:04X}h, r16\n    lds r16, 0101h\n    sts {:04X}h, r16",
            self.r0.address,
            self.r0.address + 1
        ));
        self.load_constant_into(second, 1, 1);
        self.line(&format!("    jmp {done}"));
        self.line(&format!("{not_found}:"));
        self.native_line(&format!(
            "    lds r16, 0100h\n    sts {:04X}h, r16\n    lds r16, 0101h\n    sts {:04X}h, r16",
            self.r0.address,
            self.r0.address + 1
        ));
        self.load_constant_into(second, 0, 1);
        self.line(&format!("{done}:"));
    }

    fn intrinsic_compare(&mut self, values: &[Storage]) {
        self.set_zp_from_storage(POINTER_ZP, values[0]);
        self.set_zp_from_storage(POINTER_ZP + 2, values[1]);
        self.native_line(
            "    lds r30, 0100h\n    lds r31, 0101h\n    lds r26, 0102h\n    lds r27, 0103h",
        );
        let length = values[2];
        let loop_label = self.next_label("compare_loop");
        let less = self.next_label("compare_less");
        let greater = self.next_label("compare_greater");
        let equal = self.next_label("compare_equal");
        let done = self.next_label("compare_done");
        self.line(&format!("{loop_label}:"));
        self.jump_storage_zero(length, 3, &equal);
        self.native_line("    ld r18, z+\n    ld r19, x+\n    cp r18, r19");
        self.native_line(&format!("    brlo {less}\n    brne {greater}"));
        self.decrement(length, 3);
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{less}:"));
        self.load_constant(-1, 1);
        self.line(&format!("    jmp {done}"));
        self.line(&format!("{greater}:"));
        self.load_constant(1, 1);
        self.line(&format!("    jmp {done}"));
        self.line(&format!("{equal}:"));
        self.load_constant(0, 1);
        self.line(&format!("{done}:"));
    }

    fn emit_memcpy(&mut self, args: &[Expr]) -> Result<(), Diagnostic> {
        if args.len() != 3 {
            return Err(Diagnostic::new("mem.memcpy requires three arguments"));
        }
        let pointer = Type::Ptr(Box::new(Type::Named("u8".to_owned())));
        self.emit_expr(&args[0], &pointer)?;
        let destination = self.model.allocate(2)?;
        self.copy(self.r0, destination, 2);
        self.emit_expr(&args[1], &pointer)?;
        let source = self.model.allocate(2)?;
        self.copy(self.r0, source, 2);
        self.emit_expr(&args[2], &Type::Named("u16".to_owned()))?;
        let length = self.model.allocate(2)?;
        self.copy(self.r0, length, 2);
        let loop_label = self.next_label("memcpy_loop");
        let done = self.next_label("memcpy_done");
        self.set_zp_from_storage(POINTER_ZP, source);
        self.set_zp_from_storage(POINTER_ZP + 2, destination);
        self.line(&format!("{loop_label}:"));
        self.jump_storage_zero(length, 2, &done);
        self.line("    ldy #$00");
        self.line(&format!("    lda (${:02X}),y", POINTER_ZP));
        self.line(&format!("    sta (${:02X}),y", POINTER_ZP + 2));
        self.increment_zp(POINTER_ZP);
        self.increment_zp(POINTER_ZP + 2);
        self.decrement(length, 2);
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{done}:"));
        self.zero(self.r0);
        Ok(())
    }

    fn emit_memset(&mut self, args: &[Expr]) -> Result<(), Diagnostic> {
        if args.len() != 3 {
            return Err(Diagnostic::new("mem.memset requires three arguments"));
        }
        let pointer = Type::Ptr(Box::new(Type::Named("u8".to_owned())));
        self.emit_expr(&args[0], &pointer)?;
        let destination = self.model.allocate(2)?;
        self.copy(self.r0, destination, 2);
        self.emit_expr(&args[1], &Type::Named("u8".to_owned()))?;
        let value = self.model.allocate(1)?;
        self.copy(self.r0, value, 1);
        self.emit_expr(&args[2], &Type::Named("u16".to_owned()))?;
        let length = self.model.allocate(2)?;
        self.copy(self.r0, length, 2);
        let loop_label = self.next_label("memset_loop");
        let done = self.next_label("memset_done");
        self.set_zp_from_storage(POINTER_ZP, destination);
        self.line(&format!("{loop_label}:"));
        self.jump_storage_zero(length, 2, &done);
        self.lda(value.address);
        self.line("    ldy #$00");
        self.line(&format!("    sta (${:02X}),y", POINTER_ZP));
        self.increment_zp(POINTER_ZP);
        self.decrement(length, 2);
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{done}:"));
        self.zero(self.r0);
        Ok(())
    }

    fn emit_binary_op(&mut self, op: BinaryOp, width: u8, signed: bool) -> Result<(), Diagnostic> {
        match op {
            BinaryOp::Add => self.add(width),
            BinaryOp::Sub => self.sub(width),
            BinaryOp::BitAnd | BinaryOp::BitOr | BinaryOp::BitXor => {
                for offset in 0..u32::from(width) {
                    self.lda(self.r0.address + offset);
                    let mnemonic = match op {
                        BinaryOp::BitAnd => "and",
                        BinaryOp::BitOr => "ora",
                        BinaryOp::BitXor => "eor",
                        _ => unreachable!(),
                    };
                    self.line(&format!("    {mnemonic} ${:04X}", self.r1.address + offset));
                    self.sta(self.r0.address + offset);
                }
            }
            BinaryOp::Mul => self.multiply(width, signed),
            BinaryOp::Div | BinaryOp::Mod => self.divide(width, op == BinaryOp::Mod, signed),
            BinaryOp::Shl | BinaryOp::Shr => self.shift(width, op == BinaryOp::Shr, signed),
            BinaryOp::And | BinaryOp::Or => self.logical(op),
            op if is_comparison(op) => self.compare(op, width, signed),
            _ => return Err(Diagnostic::new("unsupported AVR binary operation")),
        }
        Ok(())
    }

    fn argument_registers(&self, params: &[Type]) -> Result<Vec<Option<u8>>, Diagnostic> {
        const STARTS: [u8; 4] = [24, 22, 20, 18];
        let mut occupied = [false; 32];
        let mut registers = Vec::with_capacity(params.len());

        for (index, ty) in params.iter().enumerate() {
            let Some(&start) = STARTS.get(index) else {
                registers.push(None);
                continue;
            };
            let size = self.model.type_size(ty)?;
            let end = u32::from(start) + size;
            if end > 32 || (start..end as u8).any(|register| occupied[usize::from(register)]) {
                registers.push(None);
                continue;
            }
            for register in start..end as u8 {
                occupied[usize::from(register)] = true;
            }
            registers.push(Some(start));
        }
        Ok(registers)
    }

    fn emit_unary(&mut self, op: UnaryOp, width: u8) {
        match op {
            UnaryOp::BitNot => {
                for offset in 0..u32::from(width) {
                    self.lda(self.r0.address + offset);
                    self.line("    eor #$FF");
                    self.sta(self.r0.address + offset);
                }
            }
            UnaryOp::Neg => {
                for offset in 0..u32::from(width) {
                    self.lda(self.r0.address + offset);
                    self.line("    eor #$FF");
                    self.sta(self.r0.address + offset);
                }
                self.line("    clc");
                for offset in 0..u32::from(width) {
                    self.lda(self.r0.address + offset);
                    self.line(&format!(
                        "    adc #${:02X}",
                        if offset == 0 { 1 } else { 0 }
                    ));
                    self.sta(self.r0.address + offset);
                }
            }
            UnaryOp::Not => {
                let true_label = self.next_label("not_true");
                let done = self.next_label("not_done");
                self.jump_if_zero(self.r0.address, &true_label);
                self.load_constant(0, 1);
                self.line(&format!("    jmp {done}"));
                self.line(&format!("{true_label}:"));
                self.load_constant(1, 1);
                self.line(&format!("{done}:"));
            }
        }
    }

    fn add(&mut self, width: u8) {
        self.line("    clc");
        for offset in 0..u32::from(width) {
            self.lda(self.r0.address + offset);
            self.line(&format!("    adc ${:04X}", self.r1.address + offset));
            self.sta(self.r0.address + offset);
        }
    }

    fn sub(&mut self, width: u8) {
        self.line("    sec");
        for offset in 0..u32::from(width) {
            self.lda(self.r0.address + offset);
            self.line(&format!("    sbc ${:04X}", self.r1.address + offset));
            self.sta(self.r0.address + offset);
        }
    }

    fn multiply(&mut self, width: u8, signed: bool) {
        let lhs = self
            .model
            .allocate(u32::from(width))
            .expect("multiply lhs scratch");
        self.copy(self.r0, lhs, u32::from(width));
        self.zero(self.r0);
        self.line("    clr r20");

        for lhs_offset in 0..width {
            for rhs_offset in 0..(width - lhs_offset) {
                let result_offset = lhs_offset + rhs_offset;
                let lhs_signed = signed && lhs_offset == width - 1;
                let rhs_signed = signed && rhs_offset == width - 1;
                self.line(&format!(
                    "    lds r18, {:04X}h",
                    lhs.address + u32::from(lhs_offset)
                ));
                self.line(&format!(
                    "    lds r19, {:04X}h",
                    self.r1.address + u32::from(rhs_offset)
                ));
                match (lhs_signed, rhs_signed) {
                    (true, true) => self.line("    muls r18, r19"),
                    (true, false) => self.line("    mulsu r18, r19"),
                    (false, true) => self.line("    mulsu r19, r18"),
                    (false, false) => self.line("    mul r18, r19"),
                }
                self.line(&format!(
                    "    lds r16, {:04X}h",
                    self.r0.address + u32::from(result_offset)
                ));
                self.line("    add r16, r0");
                self.line(&format!(
                    "    sts {:04X}h, r16",
                    self.r0.address + u32::from(result_offset)
                ));
                if result_offset + 1 < width {
                    self.line(&format!(
                        "    lds r16, {:04X}h",
                        self.r0.address + u32::from(result_offset + 1)
                    ));
                    self.line("    adc r16, r1");
                    self.line(&format!(
                        "    sts {:04X}h, r16",
                        self.r0.address + u32::from(result_offset + 1)
                    ));
                    for carry_offset in result_offset + 2..width {
                        self.line(&format!(
                            "    lds r16, {:04X}h",
                            self.r0.address + u32::from(carry_offset)
                        ));
                        self.line("    adc r16, r20");
                        self.line(&format!(
                            "    sts {:04X}h, r16",
                            self.r0.address + u32::from(carry_offset)
                        ));
                    }
                }
            }
        }
        self.line("    clr r1");
    }

    fn divide(&mut self, width: u8, remainder: bool, signed: bool) {
        let loop_label = self.next_label("div_loop");
        let done = self.next_label("div_done");
        let zero = self.next_label("div_zero");
        let quotient_negative = self.model.allocate(1).expect("division sign");
        let remainder_negative = self.model.allocate(1).expect("division sign");
        self.zero(quotient_negative);
        self.zero(remainder_negative);
        if signed {
            self.lda(self.r0.address + u32::from(width - 1));
            let dividend_positive = self.next_label("dividend_positive");
            self.branch_long("bpl", &dividend_positive);
            self.toggle(quotient_negative);
            self.toggle(remainder_negative);
            self.negate_storage(self.r0, width);
            self.line(&format!("{dividend_positive}:"));
            self.normalize_signed_operand(self.r1, width, quotient_negative, true);
        }
        self.zero(self.r2);
        self.jump_storage_zero(self.r1, width, &zero);
        self.line(&format!("{loop_label}:"));
        self.jump_if_less(self.r0, self.r1, width, &done);
        self.sub(width);
        self.increment(self.r2, width);
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{zero}:"));
        self.zero(self.r0);
        self.line(&format!("    jmp {done}"));
        self.line(&format!("{done}:"));
        if !remainder {
            self.copy(self.r2, self.r0, u32::from(width));
        }
        if signed {
            self.negate_if_flag(
                self.r0,
                width,
                if remainder {
                    remainder_negative
                } else {
                    quotient_negative
                },
            );
        }
    }

    fn constant_shift_count(&self, expr: &Expr) -> Option<u8> {
        match expr {
            Expr::Int(value) | Expr::TypedInt(value, _) => Some(*value as u8),
            Expr::Ident(name) => self.model.constants.get(name).map(|value| *value as u8),
            Expr::Cast { expr, .. } => self.constant_shift_count(expr),
            _ => None,
        }
    }

    fn constant_shift(&mut self, width: u8, right: bool, signed: bool, count: u8) {
        for _ in 0..count {
            if right {
                for offset in (0..u32::from(width)).rev() {
                    self.lda(self.r0.address + offset);
                    self.line(if offset == u32::from(width - 1) {
                        if signed { "    asr r16" } else { "    lsr r16" }
                    } else {
                        "    ror r16"
                    });
                    self.sta(self.r0.address + offset);
                }
            } else {
                for offset in 0..u32::from(width) {
                    self.lda(self.r0.address + offset);
                    self.line(if offset == 0 {
                        "    lsl r16"
                    } else {
                        "    rol r16"
                    });
                    self.sta(self.r0.address + offset);
                }
            }
        }
    }

    fn shift(&mut self, width: u8, right: bool, signed: bool) {
        let loop_label = self.next_label("shift_loop");
        let done = self.next_label("shift_done");
        self.line(&format!("{loop_label}:"));
        self.jump_if_zero(self.r1.address, &done);
        if right {
            if signed {
                self.lda(self.r0.address + u32::from(width - 1));
                self.line("    asl a");
            } else {
                self.line("    clc");
            }
            for offset in (0..u32::from(width)).rev() {
                self.line(&format!("    ror ${:04X}", self.r0.address + offset));
            }
        } else {
            self.line("    clc");
            for offset in 0..u32::from(width) {
                self.line(&format!("    rol ${:04X}", self.r0.address + offset));
            }
        }
        self.line(&format!("    dec ${:04X}", self.r1.address));
        self.line(&format!("    jmp {loop_label}"));
        self.line(&format!("{done}:"));
    }

    fn logical(&mut self, op: BinaryOp) {
        let true_label = self.next_label("logic_true");
        let false_label = self.next_label("logic_false");
        let done = self.next_label("logic_done");
        match op {
            BinaryOp::And => {
                self.jump_if_zero(self.r0.address, &false_label);
                self.jump_if_zero(self.r1.address, &false_label);
                self.line(&format!("    jmp {true_label}"));
            }
            BinaryOp::Or => {
                self.jump_if_nonzero(self.r0.address, &true_label);
                self.jump_if_nonzero(self.r1.address, &true_label);
                self.line(&format!("    jmp {false_label}"));
            }
            _ => unreachable!(),
        }
        self.line(&format!("{true_label}:"));
        self.load_constant(1, 1);
        self.line(&format!("    jmp {done}"));
        self.line(&format!("{false_label}:"));
        self.load_constant(0, 1);
        self.line(&format!("{done}:"));
    }

    fn emit_short_circuit(
        &mut self,
        left: &Expr,
        op: BinaryOp,
        right: &Expr,
    ) -> Result<(), Diagnostic> {
        let decisive = self.next_label("logical_decisive");
        let done = self.next_label("logical_done");
        let bool_type = Type::Named("bool".to_owned());
        self.emit_expr(left, &bool_type)?;
        match op {
            BinaryOp::And => self.jump_if_zero(self.r0.address, &decisive),
            BinaryOp::Or => self.jump_if_nonzero(self.r0.address, &decisive),
            _ => unreachable!(),
        }
        self.emit_expr(right, &bool_type)?;
        self.line(&format!("    jmp {done}"));
        self.line(&format!("{decisive}:"));
        self.load_constant(i64::from(op == BinaryOp::Or), 1);
        self.line(&format!("{done}:"));
        Ok(())
    }

    fn compare(&mut self, op: BinaryOp, width: u8, signed: bool) {
        let true_label = self.next_label("compare_true");
        let false_label = self.next_label("compare_false");
        let done = self.next_label("compare_done");
        if signed && !matches!(op, BinaryOp::Eq | BinaryOp::Ne) {
            let top = u32::from(width - 1);
            self.lda(self.r0.address + top);
            self.line("    eor #$80");
            self.sta(self.r0.address + top);
            self.lda(self.r1.address + top);
            self.line("    eor #$80");
            self.sta(self.r1.address + top);
        }
        match op {
            BinaryOp::Eq | BinaryOp::Ne => {
                for offset in 0..u32::from(width) {
                    self.lda(self.r0.address + offset);
                    self.line(&format!("    cmp ${:04X}", self.r1.address + offset));
                    self.branch_long(
                        "bne",
                        if op == BinaryOp::Ne {
                            &true_label
                        } else {
                            &false_label
                        },
                    );
                }
                self.line(&format!(
                    "    jmp {}",
                    if op == BinaryOp::Eq {
                        &true_label
                    } else {
                        &false_label
                    }
                ));
            }
            BinaryOp::Lt | BinaryOp::Le => {
                self.jump_if_less(self.r0, self.r1, width, &true_label);
                if op == BinaryOp::Le {
                    self.jump_if_equal(self.r0, self.r1, width, &true_label);
                }
                self.line(&format!("    jmp {false_label}"));
            }
            BinaryOp::Gt | BinaryOp::Ge => {
                self.jump_if_less(self.r0, self.r1, width, &false_label);
                if op == BinaryOp::Gt {
                    self.jump_if_equal(self.r0, self.r1, width, &false_label);
                }
                self.line(&format!("    jmp {true_label}"));
            }
            _ => unreachable!(),
        }
        self.line(&format!("{true_label}:"));
        self.load_constant(1, 1);
        self.line(&format!("    jmp {done}"));
        self.line(&format!("{false_label}:"));
        self.load_constant(0, 1);
        self.line(&format!("{done}:"));
    }

    fn emit_load_place(&mut self, place: &Place, width: u8) -> Result<(), Diagnostic> {
        match self.place_address(place)? {
            Address::Direct(address) => self.copy(
                Storage {
                    address,
                    size: u32::from(width),
                },
                self.r0,
                u32::from(width),
            ),
            Address::Register(registers) => self.load_register_result(&registers),
            Address::Indirect => self.load_indirect(width),
        }
        Ok(())
    }

    fn emit_store_place(&mut self, place: &Place, width: u8) -> Result<(), Diagnostic> {
        let saved = self.model.allocate(u32::from(width))?;
        self.copy(self.r0, saved, u32::from(width));
        match self.place_address(place)? {
            Address::Direct(address) => self.copy(
                saved,
                Storage {
                    address,
                    size: u32::from(width),
                },
                u32::from(width),
            ),
            Address::Register(registers) => {
                self.copy(saved, self.r0, u32::from(width));
                self.store_result_registers(&registers);
            }
            Address::Indirect => {
                for offset in 0..u32::from(width) {
                    self.lda(saved.address + offset);
                    self.line(&format!("    ldy #${offset:02X}"));
                    self.line(&format!("    sta (${:02X}),y", POINTER_ZP));
                }
            }
        }
        Ok(())
    }

    fn emit_store_aggregate_place(
        &mut self,
        place: &Place,
        source: Storage,
        size: u32,
    ) -> Result<(), Diagnostic> {
        match self.place_address(place)? {
            Address::Direct(address) => self.copy(source, Storage { address, size }, size),
            Address::Register(_) => {
                return Err(Diagnostic::new(
                    "aggregate local cannot use a register home",
                ));
            }
            Address::Indirect => {
                for offset in 0..size {
                    self.lda(source.address + offset);
                    self.line("    ldy #$00");
                    self.line(&format!("    sta (${:02X}),y", POINTER_ZP));
                    if offset + 1 < size {
                        self.increment_zp(POINTER_ZP);
                    }
                }
            }
        }
        Ok(())
    }

    fn copy_indirect_to_storage(&mut self, storage: Storage, size: u32) {
        for offset in 0..size {
            self.line("    ldy #$00");
            self.line(&format!("    lda (${:02X}),y", POINTER_ZP));
            self.sta(storage.address + offset);
            if offset + 1 < size {
                self.increment_zp(POINTER_ZP);
            }
        }
    }

    fn place_address(&mut self, place: &Place) -> Result<Address, Diagnostic> {
        match place {
            Place::Ident(name) => {
                if let Some((address, Type::Ptr(_), _)) = self.model.mmio.get(name) {
                    Ok(Address::Direct(*address))
                } else {
                    let binding = self.binding(name)?;
                    Ok(match binding.location {
                        BindingLocation::Storage(storage) => Address::Direct(storage.address),
                        BindingLocation::Register(registers) => Address::Register(registers),
                    })
                }
            }
            Place::Index { name, index } => {
                self.emit_named_index_address(name, index)?;
                Ok(Address::Indirect)
            }
            Place::Field { base, field } => {
                let binding = self.binding(base)?;
                let layout = self.model.field(&binding.ty, field)?;
                let storage = self.binding_storage(&binding, "address register local field")?;
                Ok(Address::Direct(storage.address + layout.offset))
            }
            Place::Access(path) => {
                self.emit_access_address(path)?;
                Ok(Address::Indirect)
            }
            Place::Deref(expr) => {
                let Type::Ptr(inner) = self.model.resolved_type(&self.expr_type(expr)?)? else {
                    return Err(Diagnostic::new("dereference requires pointer"));
                };
                self.emit_expr(expr, &Type::Ptr(inner.clone()))?;
                self.copy_result_to_zp();
                Ok(Address::Indirect)
            }
        }
    }

    fn place_type(&self, place: &Place) -> Result<Type, Diagnostic> {
        match place {
            Place::Ident(name) => {
                if let Some((_, Type::Ptr(inner), _)) = self.model.mmio.get(name) {
                    Ok((**inner).clone())
                } else {
                    Ok(self.binding(name)?.ty)
                }
            }
            Place::Index { name, .. } => {
                element_type(&self.model.resolved_type(&self.binding(name)?.ty)?)
            }
            Place::Field { base, field } => {
                Ok(self.model.field(&self.binding(base)?.ty, field)?.ty.clone())
            }
            Place::Access(path) => self.access_type(path),
            Place::Deref(expr) => match self.model.resolved_type(&self.expr_type(expr)?)? {
                Type::Ptr(inner) => Ok(*inner),
                _ => Err(Diagnostic::new("dereference requires pointer")),
            },
        }
    }

    fn emit_named_index_address(&mut self, name: &str, index: &Expr) -> Result<Type, Diagnostic> {
        let binding = self.binding(name)?;
        let resolved = self.model.resolved_type(&binding.ty)?;
        let element = element_type(&resolved)?;
        let element_size = self.model.type_size(&element)?;
        match resolved {
            Type::Array { .. } => {
                let storage = self.binding_storage(&binding, "index register local as array")?;
                self.set_pointer(storage.address);
            }
            Type::Ptr(_) => {
                self.load_binding_result(&binding)?;
                self.copy_result_to_zp();
            }
            _ => return Err(Diagnostic::new("indexing requires array or pointer")),
        }
        self.add_index_to_pointer(index, element_size)?;
        Ok(element)
    }

    fn emit_access_address(&mut self, path: &AccessPath) -> Result<(Type, bool), Diagnostic> {
        let binding = self.binding(&path.root)?;
        let mut ty = self.model.resolved_type(&binding.ty)?;
        match &ty {
            Type::Ptr(_) => {
                self.load_binding_result(&binding)?;
                self.copy_result_to_zp();
                if let Type::Ptr(inner) = ty {
                    ty = *inner;
                }
            }
            _ => {
                let storage = self.binding_storage(&binding, "address register local access")?;
                self.set_pointer(storage.address);
            }
        }
        for segment in &path.segments {
            match segment {
                AccessSegment::Field(name) => {
                    let field = self.model.field(&ty, name)?.clone();
                    self.add_pointer_constant(field.offset);
                    ty = field.ty;
                }
                AccessSegment::Index(index) => {
                    let element = element_type(&self.model.resolved_type(&ty)?)?;
                    let size = self.model.type_size(&element)?;
                    self.add_index_to_pointer(index, size)?;
                    ty = element;
                }
            }
        }
        Ok((ty, true))
    }

    fn add_index_to_pointer(&mut self, index: &Expr, element_size: u32) -> Result<(), Diagnostic> {
        if let Ok(index) = self.model.const_value(index) {
            let offset = u32::try_from(index)
                .ok()
                .and_then(|index| index.checked_mul(element_size))
                .ok_or_else(|| Diagnostic::new("array index offset overflow"))?;
            self.add_pointer_constant(offset);
            return Ok(());
        }
        let saved_lo = self.model.allocate(2)?;
        self.lda(POINTER_ZP);
        self.sta(saved_lo.address);
        self.lda(POINTER_ZP + 1);
        self.sta(saved_lo.address + 1);
        self.emit_expr(index, &Type::Named("u16".to_owned()))?;
        self.lda(saved_lo.address);
        self.sta(POINTER_ZP);
        self.lda(saved_lo.address + 1);
        self.sta(POINTER_ZP + 1);
        self.scale_storage(self.r0, 2, element_size);
        self.copy(saved_lo, self.r1, 2);
        self.add(2);
        self.copy_result_to_zp();
        Ok(())
    }

    fn expr_type(&self, expr: &Expr) -> Result<Type, Diagnostic> {
        match expr {
            Expr::Int(value) => Ok(if (0..=0xFF).contains(value) {
                Type::Named("u8".to_owned())
            } else if (0..=0xFFFF).contains(value) {
                Type::Named("u16".to_owned())
            } else {
                Type::Named("u24".to_owned())
            }),
            Expr::TypedInt(_, ty) | Expr::Cast { ty, .. } => Ok(ty.clone()),
            Expr::Bool(_) => Ok(Type::Named("bool".to_owned())),
            Expr::Char(_) | Expr::In(_) => Ok(Type::Named("u8".to_owned())),
            Expr::String(_) => Ok(Type::Ptr(Box::new(Type::Named("u8".to_owned())))),
            Expr::Ident(name) => self
                .model
                .constant_types
                .get(name)
                .cloned()
                .or_else(|| self.binding(name).ok().map(|binding| binding.ty))
                .ok_or_else(|| Diagnostic::new(format!("unknown value `{name}`"))),
            Expr::Index { name, .. } => {
                element_type(&self.model.resolved_type(&self.binding(name)?.ty)?)
            }
            Expr::Field { base, field } => {
                let constant_name = format!("{base}.{field}");
                if let Some(ty) = self.model.constant_types.get(&constant_name) {
                    Ok(ty.clone())
                } else {
                    Ok(self.model.field(&self.binding(base)?.ty, field)?.ty.clone())
                }
            }
            Expr::AddressOfIndex { name, .. } => Ok(Type::Ptr(Box::new(element_type(
                &self.model.resolved_type(&self.binding(name)?.ty)?,
            )?))),
            Expr::AddressOfField { base, field } => Ok(Type::Ptr(Box::new(
                self.model.field(&self.binding(base)?.ty, field)?.ty.clone(),
            ))),
            Expr::Access(path) => self.access_type(path),
            Expr::AddressOfAccess(path) => Ok(Type::Ptr(Box::new(self.access_type(path)?))),
            Expr::AddressOf(name) => {
                if let Some(function_ty) = self.function_value_type(name) {
                    Ok(Type::Ptr(Box::new(function_ty)))
                } else if self
                    .model
                    .functions
                    .get(name)
                    .is_some_and(|signature| signature.second_return_type.is_some())
                {
                    Err(Diagnostic::new(format!(
                        "AVR function pointer cannot reference two-result function `{name}`"
                    )))
                } else {
                    Ok(Type::Ptr(Box::new(self.binding(name)?.ty)))
                }
            }
            Expr::StructInit { ty, .. } => Ok(Type::Named(ty.clone())),
            Expr::BankedPointer { pointer, .. } => self.expr_type(pointer),
            Expr::Deref(expr) => match self.model.resolved_type(&self.expr_type(expr)?)? {
                Type::Ptr(inner) => Ok(*inner),
                _ => Err(Diagnostic::new("dereference requires pointer")),
            },
            Expr::Call { path, args } => {
                let name = path.join(".");
                if let Some(descriptor) = CATALOG.lookup(&name) {
                    let argument_types = args
                        .iter()
                        .map(|arg| self.model.resolved_type(&self.expr_type(arg)?))
                        .collect::<Result<Vec<_>, _>>()?;
                    let result = CATALOG
                        .infer_result_types(descriptor.canonical_name, &argument_types)
                        .map_err(|error| Diagnostic::new(error.to_string()))?;
                    return result.into_iter().next().ok_or_else(|| {
                        Diagnostic::new(format!("intrinsic `{name}` has no scalar result"))
                    });
                }
                if let Some(name) = resolve_called_function(path, &self.model) {
                    return self.model.functions[&name]
                        .return_type
                        .clone()
                        .ok_or_else(|| Diagnostic::new("void function has no value"));
                }
                if path.len() == 1
                    && let Type::Ptr(inner) =
                        self.model.resolved_type(&self.binding(&path[0])?.ty)?
                    && let Type::Function { return_type, .. } = *inner
                {
                    return return_type
                        .map(|ty| *ty)
                        .ok_or_else(|| Diagnostic::new("void function has no value"));
                }
                Err(Diagnostic::new(format!(
                    "unknown function `{}`",
                    path.join(".")
                )))
            }
            Expr::Unary {
                op: UnaryOp::Not, ..
            } => Ok(Type::Named("bool".to_owned())),
            Expr::Unary { expr, .. } => self.expr_type(expr),
            Expr::Binary { left, op, .. }
                if is_comparison(*op) || matches!(op, BinaryOp::And | BinaryOp::Or) =>
            {
                let _ = left;
                Ok(Type::Named("bool".to_owned()))
            }
            Expr::Binary { left, .. } => self.expr_type(left),
            Expr::Array(_) => Err(Diagnostic::new("array type requires context")),
        }
    }

    fn access_type(&self, path: &AccessPath) -> Result<Type, Diagnostic> {
        let mut ty = self.model.resolved_type(&self.binding(&path.root)?.ty)?;
        if let Type::Ptr(inner) = ty {
            ty = *inner;
        }
        for segment in &path.segments {
            ty = match segment {
                AccessSegment::Field(name) => self.model.field(&ty, name)?.ty.clone(),
                AccessSegment::Index(_) => element_type(&self.model.resolved_type(&ty)?)?,
            };
        }
        Ok(ty)
    }

    fn emit_inline_asm(
        &mut self,
        inputs: &[crate::ast::AsmInput],
        outputs: &[crate::ast::AsmOutput],
        lines: &[String],
    ) -> Result<(), Diagnostic> {
        let mut operands = HashMap::new();
        for input in inputs {
            let binding = self.binding(&input.name)?;
            let storage = self.binding_storage(&binding, "use register local in inline asm")?;
            operands.insert(input.name.clone(), format!("{:04X}h", storage.address));
        }
        for output in outputs {
            let binding = self.binding(&output.name)?;
            let storage = self.binding_storage(&binding, "use register local in inline asm")?;
            operands.insert(output.name.clone(), format!("{:04X}h", storage.address));
        }
        let local_label_prefix = self.next_label("asm");
        for line in lines {
            let mut emitted = rewrite_local_labels(line, &local_label_prefix);
            for (name, value) in &operands {
                emitted = emitted.replace(&format!("{{{name}}}"), value);
            }
            if emitted.contains(['{', '}']) {
                return Err(Diagnostic::new(format!(
                    "unknown inline asm operand placeholder in `{line}`"
                )));
            }
            self.line(&format!("    {emitted}"));
        }
        Ok(())
    }

    fn bind_storage(&mut self, name: String, storage: Storage, ty: Type) -> Result<(), Diagnostic> {
        if self
            .scopes
            .iter()
            .rev()
            .any(|scope| scope.contains_key(&name))
        {
            return Err(Diagnostic::new(format!(
                "local `{name}` shadows an existing name"
            )));
        }
        self.scopes.last_mut().expect("function scope").insert(
            name,
            Binding {
                location: BindingLocation::Storage(storage),
                ty,
            },
        );
        Ok(())
    }

    fn binding(&self, name: &str) -> Result<Binding, Diagnostic> {
        if let Some(binding) = self.scopes.iter().rev().find_map(|scope| scope.get(name)) {
            return Ok(binding.clone());
        }
        if let Some(storage) = self.model.globals.get(name) {
            return Ok(Binding {
                location: BindingLocation::Storage(*storage),
                ty: self.model.global_types[name].clone(),
            });
        }
        if let Some(embed) = self.model.embeds.get(name) {
            return Ok(Binding {
                location: BindingLocation::Storage(embed.storage),
                ty: embed.ty.clone(),
            });
        }
        Err(Diagnostic::new(format!("unknown variable `{name}`")))
    }

    fn binding_storage(&self, binding: &Binding, operation: &str) -> Result<Storage, Diagnostic> {
        match binding.location {
            BindingLocation::Storage(storage) => Ok(storage),
            BindingLocation::Register(_) => Err(Diagnostic::new(format!(
                "cannot {operation}; register allocator should have forced this local to memory"
            ))),
        }
    }

    fn load_binding_result(&mut self, binding: &Binding) -> Result<(), Diagnostic> {
        match &binding.location {
            BindingLocation::Storage(storage) => {
                let width = self.model.type_width(&binding.ty)?;
                self.copy(*storage, self.r0, u32::from(width));
            }
            BindingLocation::Register(registers) => self.load_register_result(registers),
        }
        Ok(())
    }

    fn store_binding_result(&mut self, binding: &Binding) -> Result<(), Diagnostic> {
        match &binding.location {
            BindingLocation::Storage(storage) => {
                let width = self.model.type_width(&binding.ty)?;
                self.copy(self.r0, *storage, u32::from(width));
            }
            BindingLocation::Register(registers) => self.store_result_registers(registers),
        }
        Ok(())
    }

    fn load_register_result(&mut self, registers: &[u8]) {
        for (offset, register) in registers.iter().enumerate() {
            self.line(&format!("    mov r16, r{register}"));
            self.line(&format!(
                "    sts {:04X}h, r16",
                self.r0.address + offset as u32
            ));
        }
    }

    fn store_result_registers(&mut self, registers: &[u8]) {
        for (offset, register) in registers.iter().enumerate() {
            self.line(&format!(
                "    lds r16, {:04X}h",
                self.r0.address + offset as u32
            ));
            self.line(&format!("    mov r{register}, r16"));
        }
    }

    fn copy(&mut self, source: Storage, target: Storage, size: u32) {
        for offset in 0..size {
            self.lda(source.address + offset);
            self.sta(target.address + offset);
        }
    }

    fn zero(&mut self, storage: Storage) {
        self.lda_imm(0);
        for offset in 0..storage.size {
            self.sta(storage.address + offset);
        }
    }

    fn load_constant(&mut self, value: i64, width: u8) {
        self.load_constant_into(self.r0, value, width);
    }

    fn load_constant_into(&mut self, target: Storage, value: i64, width: u8) {
        for offset in 0..u32::from(width) {
            self.lda_imm(((value as u64 >> (offset * 8)) & 0xFF) as u8);
            self.sta(target.address + offset);
        }
    }

    fn extend_result(&mut self, source_width: u8, target_width: u8, signed: bool) {
        if target_width <= source_width {
            return;
        }
        if signed {
            let positive = self.next_label("extend_positive");
            let done = self.next_label("extend_done");
            self.lda(self.r0.address + u32::from(source_width - 1));
            self.branch_long("bpl", &positive);
            self.lda_imm(0xFF);
            self.line(&format!("    jmp {done}"));
            self.line(&format!("{positive}:"));
            self.lda_imm(0);
            self.line(&format!("{done}:"));
        } else {
            self.lda_imm(0);
        }
        for offset in u32::from(source_width)..u32::from(target_width) {
            self.sta(self.r0.address + offset);
        }
    }

    fn scale_storage(&mut self, storage: Storage, width: u8, mut scale: u32) {
        if scale <= 1 {
            return;
        }
        if scale.is_power_of_two() {
            self.copy(storage, self.r0, u32::from(width));
            self.constant_shift(width, false, false, scale.trailing_zeros() as u8);
            self.copy(self.r0, storage, u32::from(width));
            return;
        }

        let source = self
            .model
            .allocate(u32::from(width))
            .expect("pointer scale source");
        let result = self
            .model
            .allocate(u32::from(width))
            .expect("pointer scale result");
        self.copy(storage, source, u32::from(width));
        self.zero(result);
        while scale != 0 {
            if scale & 1 != 0 {
                self.copy(result, self.r0, u32::from(width));
                self.copy(source, self.r1, u32::from(width));
                self.add(width);
                self.copy(self.r0, result, u32::from(width));
            }
            scale >>= 1;
            if scale != 0 {
                self.copy(source, self.r0, u32::from(width));
                self.constant_shift(width, false, false, 1);
                self.copy(self.r0, source, u32::from(width));
            }
        }
        self.copy(result, storage, u32::from(width));
    }

    fn normalize_signed_operand(
        &mut self,
        storage: Storage,
        width: u8,
        negative: Storage,
        toggle_sign: bool,
    ) {
        let positive = self.next_label("signed_positive");
        self.lda(storage.address + u32::from(width - 1));
        self.branch_long("bpl", &positive);
        if toggle_sign {
            self.toggle(negative);
        } else {
            self.lda_imm(1);
            self.sta(negative.address);
        }
        self.negate_storage(storage, width);
        self.line(&format!("{positive}:"));
    }

    fn negate_if_flag(&mut self, storage: Storage, width: u8, flag: Storage) {
        let done = self.next_label("sign_done");
        self.jump_if_zero(flag.address, &done);
        self.negate_storage(storage, width);
        self.line(&format!("{done}:"));
    }

    fn negate_storage(&mut self, storage: Storage, width: u8) {
        for offset in 0..u32::from(width) {
            self.lda(storage.address + offset);
            self.line("    eor #$FF");
            self.sta(storage.address + offset);
        }
        self.line("    clc");
        for offset in 0..u32::from(width) {
            self.lda(storage.address + offset);
            self.line(&format!(
                "    adc #${:02X}",
                if offset == 0 { 1 } else { 0 }
            ));
            self.sta(storage.address + offset);
        }
    }

    fn toggle(&mut self, storage: Storage) {
        self.lda(storage.address);
        self.line("    eor #$01");
        self.sta(storage.address);
    }

    fn set_zp_from_storage(&mut self, zero_page: u32, storage: Storage) {
        self.lda(storage.address);
        self.sta(zero_page);
        self.lda(storage.address + 1);
        self.sta(zero_page + 1);
    }

    fn increment_zp(&mut self, zero_page: u32) {
        let done = self.next_label("pointer_incremented");
        self.line(&format!("    inc ${zero_page:02X}"));
        self.branch_long("bne", &done);
        self.line(&format!("    inc ${:02X}", zero_page + 1));
        self.line(&format!("{done}:"));
    }

    fn set_pointer(&mut self, address: u32) {
        self.lda_imm(address as u8);
        self.sta(POINTER_ZP);
        self.lda_imm((address >> 8) as u8);
        self.sta(POINTER_ZP + 1);
    }

    fn add_pointer_constant(&mut self, value: u32) {
        self.line("    clc");
        self.lda(POINTER_ZP);
        self.line(&format!("    adc #${:02X}", value as u8));
        self.sta(POINTER_ZP);
        self.lda(POINTER_ZP + 1);
        self.line(&format!("    adc #${:02X}", (value >> 8) as u8));
        self.sta(POINTER_ZP + 1);
    }

    fn copy_result_to_zp(&mut self) {
        self.lda(self.r0.address);
        self.sta(POINTER_ZP);
        self.lda(self.r0.address + 1);
        self.sta(POINTER_ZP + 1);
    }

    fn copy_zp_to_result(&mut self, width: u8) {
        self.lda(POINTER_ZP);
        self.sta(self.r0.address);
        self.lda(POINTER_ZP + 1);
        self.sta(self.r0.address + 1);
        for offset in 2..u32::from(width) {
            self.lda_imm(0);
            self.sta(self.r0.address + offset);
        }
    }

    fn load_indirect(&mut self, width: u8) {
        for offset in 0..u32::from(width) {
            self.line(&format!("    ldy #${offset:02X}"));
            self.line(&format!("    lda (${:02X}),y", POINTER_ZP));
            self.sta(self.r0.address + offset);
        }
    }

    fn copy_storage_to_indirect(&mut self, source: Storage, size: u32) {
        for offset in 0..size {
            self.lda(source.address + offset);
            self.line(&format!("    ldy #${offset:02X}"));
            self.line(&format!("    sta (${:02X}),y", POINTER_ZP));
        }
    }

    fn increment(&mut self, storage: Storage, width: u8) {
        let done = self.next_label("increment_done");
        for offset in 0..u32::from(width) {
            self.line(&format!("    inc ${:04X}", storage.address + offset));
            self.branch_long("bne", &done);
        }
        self.line(&format!("{done}:"));
    }

    fn decrement(&mut self, storage: Storage, width: u8) {
        self.line("    sec");
        for offset in 0..u32::from(width) {
            self.lda(storage.address + offset);
            self.line(&format!(
                "    sbc #${:02X}",
                if offset == 0 { 1 } else { 0 }
            ));
            self.sta(storage.address + offset);
        }
    }

    fn jump_storage_zero(&mut self, storage: Storage, width: u8, label: &str) {
        let nonzero = self.next_label("nonzero");
        for offset in 0..u32::from(width) {
            self.jump_if_nonzero(storage.address + offset, &nonzero);
        }
        self.line(&format!("    jmp {label}"));
        self.line(&format!("{nonzero}:"));
    }

    fn jump_if_equal(&mut self, left: Storage, right: Storage, width: u8, label: &str) {
        let different = self.next_label("different");
        for offset in 0..u32::from(width) {
            self.lda(left.address + offset);
            self.line(&format!("    cmp ${:04X}", right.address + offset));
            self.branch_long("bne", &different);
        }
        self.line(&format!("    jmp {label}"));
        self.line(&format!("{different}:"));
    }

    fn jump_if_less(&mut self, left: Storage, right: Storage, width: u8, label: &str) {
        let done = self.next_label("compare_ordered");
        for offset in (0..u32::from(width)).rev() {
            self.lda(left.address + offset);
            self.line(&format!("    cmp ${:04X}", right.address + offset));
            self.branch_long("bcc", label);
            self.branch_long("bne", &done);
        }
        self.line(&format!("{done}:"));
    }

    fn jump_if_zero(&mut self, address: u32, label: &str) {
        self.lda(address);
        self.branch_long("beq", label);
    }

    fn jump_if_nonzero(&mut self, address: u32, label: &str) {
        self.lda(address);
        self.branch_long("bne", label);
    }

    fn branch_long(&mut self, branch: &str, target: &str) {
        let skip = self.next_label("branch_skip");
        let inverse = match branch {
            "beq" => "bne",
            "bne" => "beq",
            "bcc" => "bcs",
            "bcs" => "bcc",
            "bpl" => "bmi",
            "bmi" => "bpl",
            _ => unreachable!("unsupported branch"),
        };
        self.line(&format!("    {inverse} {skip}"));
        self.line(&format!("    jmp {target}"));
        self.line(&format!("{skip}:"));
    }

    fn lda(&mut self, address: u32) {
        self.line(&format!("    lda ${address:04X}"));
    }

    fn sta(&mut self, address: u32) {
        self.line(&format!("    sta ${address:04X}"));
    }

    fn lda_imm(&mut self, value: u8) {
        self.line(&format!("    lda #${value:02X}"));
    }

    fn next_label(&mut self, name: &str) -> String {
        let label = format!(".L_{}_{}", sanitize(name), self.labels);
        self.labels += 1;
        label
    }

    fn line(&mut self, line: &str) {
        let translated = translate_avr_line(line);
        self.out.push_str(&translated);
        self.out.push('\n');
    }

    fn native_line(&mut self, line: &str) {
        self.out.push_str(line);
        self.out.push('\n');
    }
}

const AVR_LOCAL_FIRST_REGISTER: u8 = 2;
const AVR_LOCAL_LAST_REGISTER: u8 = 15;
const AVR_STATIC_SPILL_CLASS: SpillClassId = SpillClassId(0);

fn avr_local_target() -> Target {
    let units = (AVR_LOCAL_FIRST_REGISTER..=AVR_LOCAL_LAST_REGISTER)
        .map(|register| RegisterUnit::new(format!("r{register}")))
        .collect::<Vec<_>>();
    let mut registers = Vec::new();
    let mut classes = Vec::new();

    for width in 1..=4_usize {
        let mut class_registers = Vec::new();
        for first_unit in (0..units.len()).step_by(width) {
            if first_unit + width > units.len() {
                break;
            }
            let physical = PhysReg(registers.len());
            let first_register = AVR_LOCAL_FIRST_REGISTER + first_unit as u8;
            let last_register = first_register + width as u8 - 1;
            registers.push(PhysicalRegister::new(
                if width == 1 {
                    format!("r{first_register}")
                } else {
                    format!("r{first_register}:r{last_register}")
                },
                (first_unit..first_unit + width).map(RegUnit).collect(),
            ));
            class_registers.push(physical);
        }
        classes.push(RegisterClass::new(
            format!("scalar-{width}-byte"),
            class_registers,
        ));
    }

    Target {
        units,
        registers,
        register_classes: classes,
        spill_classes: vec![
            SpillClass::new("static", None, 1).for_register_classes(vec![
                RegClass(0),
                RegClass(1),
                RegClass(2),
                RegClass(3),
            ]),
        ],
    }
}

fn plan_function_locals(
    function: &Function,
    model: &mut SemanticModel,
) -> Result<FunctionLocals, Diagnostic> {
    let mut source_locals = Vec::new();
    let mut local_types = HashMap::new();
    collect_avr_locals(&function.body, model, &mut source_locals, &mut local_types)?;

    let target = avr_local_target();
    let clobbers = (0..target.registers.len()).map(PhysReg).collect::<Vec<_>>();
    let planned = allocate_source_locals(&target, &source_locals, &function.body, &clobbers)
        .map_err(|diagnostics| {
            Diagnostic::new(
                diagnostics
                    .into_iter()
                    .map(|diagnostic| diagnostic.message)
                    .collect::<Vec<_>>()
                    .join("; "),
            )
        })?;
    let spill_bytes = planned
        .allocation
        .spill_slots
        .iter()
        .map(|slot| slot.offset.saturating_add(slot.size))
        .max()
        .unwrap_or(0);
    let spill_storage = (spill_bytes != 0)
        .then(|| model.allocate(spill_bytes))
        .transpose()?;

    let mut bindings = HashMap::new();
    for (name, ty) in local_types {
        let vreg = planned
            .locals
            .vreg(&name)
            .ok_or_else(|| Diagnostic::new(format!("missing allocation for local `{name}`")))?;
        let location = match planned.allocation.location(vreg) {
            Some(Location::Register(register)) => {
                let physical = target.registers.get(register.0).ok_or_else(|| {
                    Diagnostic::new(format!("invalid AVR local register for `{name}`"))
                })?;
                BindingLocation::Register(
                    physical
                        .units
                        .iter()
                        .map(|unit| AVR_LOCAL_FIRST_REGISTER + unit.0 as u8)
                        .collect(),
                )
            }
            Some(Location::Spill(slot_index)) => {
                let slot = planned
                    .allocation
                    .spill_slots
                    .get(slot_index)
                    .ok_or_else(|| Diagnostic::new(format!("invalid spill slot for `{name}`")))?;
                debug_assert_eq!(slot.class, AVR_STATIC_SPILL_CLASS);
                let backing = spill_storage.ok_or_else(|| {
                    Diagnostic::new(format!("missing AVR spill storage for `{name}`"))
                })?;
                BindingLocation::Storage(Storage {
                    address: backing.address + slot.offset,
                    size: model.type_size(&ty)?,
                })
            }
            Some(Location::Unused) | None => {
                return Err(Diagnostic::new(format!(
                    "source allocator did not place local `{name}`"
                )));
            }
        };
        bindings.insert(name, Binding { location, ty });
    }
    Ok(FunctionLocals { bindings })
}

fn collect_avr_locals(
    body: &[Stmt],
    model: &SemanticModel,
    locals: &mut Vec<SourceLocal>,
    local_types: &mut HashMap<String, Type>,
) -> Result<(), Diagnostic> {
    for stmt in body {
        match stmt {
            Stmt::Let { name, ty, .. } => {
                collect_avr_local(name, ty, false, model, locals, local_types)?;
            }
            Stmt::LetTwo {
                first_name,
                first_ty,
                second_name,
                second_ty,
                ..
            } => {
                collect_avr_local(first_name, first_ty, false, model, locals, local_types)?;
                collect_avr_local(second_name, second_ty, true, model, locals, local_types)?;
            }
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_avr_locals(then_body, model, locals, local_types)?;
                collect_avr_locals(else_body, model, locals, local_types)?;
            }
            Stmt::While { body, .. } | Stmt::Loop { body } => {
                collect_avr_locals(body, model, locals, local_types)?;
            }
            _ => {}
        }
    }
    Ok(())
}

fn collect_avr_local(
    name: &str,
    ty: &Type,
    force_memory: bool,
    model: &SemanticModel,
    locals: &mut Vec<SourceLocal>,
    local_types: &mut HashMap<String, Type>,
) -> Result<(), Diagnostic> {
    let ty = model.resolved_type(ty)?;
    let width = model.type_width(&ty).ok();
    let size = match width {
        Some(width) => u32::from(width),
        None => model.type_size(&ty)?,
    };
    if local_types.insert(name.to_owned(), ty).is_some() {
        return Err(Diagnostic::new(format!("duplicate local `{name}")));
    }
    locals.push(
        SourceLocal::new(
            name.to_owned(),
            size,
            1,
            RegClass(usize::from(width.unwrap_or(1) - 1)),
        )
        .with_spill_classes(vec![AVR_STATIC_SPILL_CLASS])
        .with_force_memory(force_memory || width.is_none()),
    );
    Ok(())
}

fn contains_two_result_statement(stmts: &[Stmt]) -> bool {
    stmts.iter().any(|stmt| match stmt {
        Stmt::ReturnTwo { .. } => true,
        Stmt::If {
            then_body,
            else_body,
            ..
        } => contains_two_result_statement(then_body) || contains_two_result_statement(else_body),
        Stmt::While { body, .. } | Stmt::Loop { body } => contains_two_result_statement(body),
        _ => false,
    })
}

fn block_can_complete_normally(stmts: &[Stmt], model: &SemanticModel) -> bool {
    let mut reachable = true;
    for stmt in stmts {
        if !reachable {
            break;
        }
        reachable = stmt_can_complete_normally(stmt, model);
    }
    reachable
}

fn stmt_can_complete_normally(stmt: &Stmt, model: &SemanticModel) -> bool {
    match stmt {
        Stmt::Return(_) | Stmt::ReturnTwo { .. } | Stmt::Break | Stmt::Continue => false,
        Stmt::If {
            condition,
            then_body,
            else_body,
        } => match model.const_value(condition) {
            Ok(0) => block_can_complete_normally(else_body, model),
            Ok(_) => block_can_complete_normally(then_body, model),
            Err(_) => {
                block_can_complete_normally(then_body, model)
                    || block_can_complete_normally(else_body, model)
            }
        },
        Stmt::Loop { body } => block_can_break_current_loop(body, model),
        Stmt::While { condition, body } => {
            !condition_is_const_true(condition, model) || block_can_break_current_loop(body, model)
        }
        _ => true,
    }
}

fn condition_is_const_true(condition: &Expr, model: &SemanticModel) -> bool {
    matches!(condition, Expr::Bool(true))
        || matches!(condition, Expr::Ident(name) if name == "true")
        || model.const_value(condition).is_ok_and(|value| value != 0)
}

fn block_can_break_current_loop(stmts: &[Stmt], model: &SemanticModel) -> bool {
    let mut reachable = true;
    for stmt in stmts {
        if !reachable {
            break;
        }
        if stmt_can_break_current_loop(stmt, model) {
            return true;
        }
        reachable = stmt_can_complete_normally(stmt, model);
    }
    false
}

fn stmt_can_break_current_loop(stmt: &Stmt, model: &SemanticModel) -> bool {
    match stmt {
        Stmt::Break => true,
        Stmt::If {
            condition,
            then_body,
            else_body,
        } => match model.const_value(condition) {
            Ok(0) => block_can_break_current_loop(else_body, model),
            Ok(_) => block_can_break_current_loop(then_body, model),
            Err(_) => {
                block_can_break_current_loop(then_body, model)
                    || block_can_break_current_loop(else_body, model)
            }
        },
        Stmt::While { .. } | Stmt::Loop { .. } => false,
        _ => false,
    }
}

fn translate_avr_line(line: &str) -> String {
    let indent = if line.starts_with("    ") { "    " } else { "" };
    let text = line.trim();
    if text.is_empty()
        || text.starts_with(';')
        || text.starts_with("section ")
        || text.ends_with(':')
    {
        return line.to_owned();
    }
    let (op, arg) = text.split_once(' ').unwrap_or((text, ""));
    let arg = arg.trim();
    let hex = |s: &str| s.trim_start_matches('#').trim_start_matches('$').to_owned() + "h";
    let direct = |s: &str| hex(s);
    let two = |avr: &str, rhs: &str| format!("    lds r17, {}\n    {avr} r16, r17", direct(rhs));
    match op {
        "lda" if arg.starts_with('#') => format!("{indent}ldi r16, {}\n    tst r16", hex(arg)),
        "lda" if arg.starts_with('(') => "    lds r30, 0100h\n    lds r31, 0101h\n    add r30, r17\n    adc r31, r1\n    ld r16, z\n    tst r16".to_owned(),
        "lda" => format!("{indent}lds r16, {}\n    tst r16", direct(arg)),
        "sta" if arg.starts_with('(') => "    lds r30, 0100h\n    lds r31, 0101h\n    add r30, r17\n    adc r31, r1\n    st z, r16".to_owned(),
        "sta" => format!("{indent}sts {}, r16", direct(arg)),
        "ldy" => format!("{indent}ldi r17, {}", hex(arg)),
        "jsr" => format!("{indent}call {arg}"),
        "rts" => format!("{indent}ret"),
        "rti" => format!("{indent}reti"),
        "pha" => format!("{indent}push r16"),
        "pla" => format!("{indent}pop r16\n    tst r16"),
        "txa" | "tya" | "tax" | "tay" => format!("{indent}nop"),
        "ora" => two("or", arg),
        "and" => two("and", arg),
        "eor" if arg.starts_with('#') => format!("    ldi r17, {}\n    eor r16, r17", hex(arg)),
        "eor" => two("eor", arg),
        "adc" if arg.starts_with('#') => format!("    ldi r17, {}\n    adc r16, r17", hex(arg)),
        "adc" if arg.starts_with('r') => line.to_owned(),
        "adc" => two("adc", arg),
        "sbc" if arg.starts_with('#') => format!("    ldi r17, {}\n    sbc r16, r17", hex(arg)),
        "sbc" => two("sbc", arg),
        "cmp" => two("cp", arg),
        "asl" if arg == "a" => "    lsl r16".to_owned(),
        "rol" | "ror" if arg == "r16" => line.to_owned(),
        "inc" | "dec" if arg.starts_with('r') => line.to_owned(),
        "inc" | "dec" | "rol" | "ror" | "asl" => format!("    lds r16, {}\n    {} r16\n    sts {}, r16", direct(arg), if op == "asl" { "lsl" } else { op }, direct(arg)),
        "beq" => format!("{indent}breq {arg}"),
        "bne" => format!("{indent}brne {arg}"),
        // 6502 carry is set for no borrow, while AVR carry is set for borrow.
        // Invert carry branches so lowered comparisons retain their meaning.
        "bcc" => format!("{indent}brcs {arg}"),
        "bcs" => format!("{indent}brcc {arg}"),
        "bpl" => format!("{indent}brpl {arg}"),
        "bmi" => format!("{indent}brmi {arg}"),
        "sec" => format!("{indent}clc"),
        "clc" | "cli" | "sei" | "jmp" | "call" | "ret" | "reti" | "nop" => line.to_owned(),
        _ => line.to_owned(),
    }
}

enum Address {
    Direct(u32),
    Register(Vec<u8>),
    Indirect,
}

fn intrinsic_constant(constants: &[Option<i64>], index: usize) -> Result<u32, Diagnostic> {
    let value = constants
        .get(index)
        .copied()
        .flatten()
        .ok_or_else(|| Diagnostic::new("intrinsic bit range must be compile-time constants"))?;
    u32::try_from(value).map_err(|_| Diagnostic::new("intrinsic bit range must be non-negative"))
}

fn intrinsic_mask(bits: u32) -> u32 {
    if bits >= 32 {
        u32::MAX
    } else if bits == 0 {
        0
    } else {
        (1_u32 << bits) - 1
    }
}

fn element_type(ty: &Type) -> Result<Type, Diagnostic> {
    match ty {
        Type::Array { element, .. } | Type::Ptr(element) => Ok((**element).clone()),
        _ => Err(Diagnostic::new("indexing requires array or pointer")),
    }
}

fn type_is_signed(ty: &Type) -> bool {
    matches!(ty, Type::Named(name) if name.starts_with('i'))
}

fn is_comparison(op: BinaryOp) -> bool {
    matches!(
        op,
        BinaryOp::Eq | BinaryOp::Ne | BinaryOp::Lt | BinaryOp::Le | BinaryOp::Gt | BinaryOp::Ge
    )
}

fn assign_binary(op: AssignOp) -> BinaryOp {
    match op {
        AssignOp::Add => BinaryOp::Add,
        AssignOp::Sub => BinaryOp::Sub,
        AssignOp::Mul => BinaryOp::Mul,
        AssignOp::Div => BinaryOp::Div,
        AssignOp::Mod => BinaryOp::Mod,
        AssignOp::BitAnd => BinaryOp::BitAnd,
        AssignOp::BitOr => BinaryOp::BitOr,
        AssignOp::BitXor => BinaryOp::BitXor,
        AssignOp::Shl => BinaryOp::Shl,
        AssignOp::Shr => BinaryOp::Shr,
        AssignOp::Set => unreachable!(),
    }
}

fn contains_function_pointer_program(program: &Program) -> bool {
    let function_names = program
        .declarations
        .iter()
        .filter_map(|declaration| match declaration {
            Declaration::Function(function) => Some(function.name.clone()),
            Declaration::ExternAsmFunction(function) => Some(function.name.clone()),
            _ => None,
        })
        .collect::<HashSet<_>>();
    program
        .declarations
        .iter()
        .any(|declaration| match declaration {
            Declaration::Function(function) => {
                function
                    .params
                    .iter()
                    .any(|param| type_contains_function_pointer(&param.ty))
                    || function
                        .return_type
                        .as_ref()
                        .is_some_and(type_contains_function_pointer)
                    || function
                        .second_return_type
                        .as_ref()
                        .is_some_and(type_contains_function_pointer)
                    || function_body_contains_function_pointer(&function.body, &function_names)
            }
            Declaration::Global(global) => {
                type_contains_function_pointer(&global.ty)
                    || expr_contains_function_pointer(&global.value, &function_names)
            }
            _ => false,
        })
}

fn type_contains_function_pointer(ty: &Type) -> bool {
    match ty {
        Type::Ptr(inner) | Type::Array { element: inner, .. } => {
            type_contains_function_pointer(inner)
        }
        Type::Function { .. } => true,
        Type::Named(_) => false,
    }
}

fn function_body_contains_function_pointer(
    body: &[Stmt],
    function_names: &HashSet<String>,
) -> bool {
    body.iter().any(|stmt| match stmt {
        Stmt::Let { ty, value, .. } => {
            type_contains_function_pointer(ty)
                || expr_contains_function_pointer(value, function_names)
        }
        Stmt::LetTwo {
            first_ty,
            second_ty,
            value,
            ..
        } => {
            type_contains_function_pointer(first_ty)
                || type_contains_function_pointer(second_ty)
                || expr_contains_function_pointer(value, function_names)
        }
        Stmt::Return(Some(value)) | Stmt::Expr(value) | Stmt::Out { value, .. } => {
            expr_contains_function_pointer(value, function_names)
        }
        Stmt::ReturnTwo { first, second } => {
            expr_contains_function_pointer(first, function_names)
                || expr_contains_function_pointer(second, function_names)
        }
        Stmt::Assign { value, .. } => expr_contains_function_pointer(value, function_names),
        Stmt::If {
            condition,
            then_body,
            else_body,
        } => {
            expr_contains_function_pointer(condition, function_names)
                || function_body_contains_function_pointer(then_body, function_names)
                || function_body_contains_function_pointer(else_body, function_names)
        }
        Stmt::While { condition, body } => {
            expr_contains_function_pointer(condition, function_names)
                || function_body_contains_function_pointer(body, function_names)
        }
        Stmt::Loop { body } => function_body_contains_function_pointer(body, function_names),
        Stmt::Return(None) | Stmt::Break | Stmt::Continue | Stmt::Asm { .. } => false,
    })
}

fn expr_contains_function_pointer(expr: &Expr, function_names: &HashSet<String>) -> bool {
    match expr {
        Expr::AddressOf(name) => function_names.contains(name),
        Expr::Cast { ty, expr } => {
            type_contains_function_pointer(ty)
                || expr_contains_function_pointer(expr, function_names)
        }
        Expr::Array(values) => values
            .iter()
            .any(|value| expr_contains_function_pointer(value, function_names)),
        Expr::Index { index, .. } | Expr::AddressOfIndex { index, .. } => {
            expr_contains_function_pointer(index, function_names)
        }
        Expr::Access(path) | Expr::AddressOfAccess(path) => path.segments.iter().any(|segment| {
            matches!(segment, AccessSegment::Index(index) if expr_contains_function_pointer(index, function_names))
        }),
        Expr::StructInit { fields, .. } => fields
            .iter()
            .any(|(_, value)| expr_contains_function_pointer(value, function_names)),
        Expr::Deref(value)
        | Expr::BankedPointer { pointer: value, .. }
        | Expr::Unary { expr: value, .. } => expr_contains_function_pointer(value, function_names),
        Expr::Call { args, .. } => args
            .iter()
            .any(|arg| expr_contains_function_pointer(arg, function_names)),
        Expr::Binary { left, right, .. } => {
            expr_contains_function_pointer(left, function_names)
                || expr_contains_function_pointer(right, function_names)
        }
        Expr::Int(_)
        | Expr::TypedInt(_, _)
        | Expr::Bool(_)
        | Expr::Char(_)
        | Expr::String(_)
        | Expr::Ident(_)
        | Expr::In(_)
        | Expr::Field { .. }
        | Expr::AddressOfField { .. } => false,
    }
}

fn reachable_function_names(program: &Program, model: &SemanticModel) -> HashSet<String> {
    let mut graph = HashMap::new();
    let mut roots = vec!["main".to_owned()];

    for declaration in &program.declarations {
        match declaration {
            Declaration::Function(function) => {
                let mut calls = Vec::new();
                collect_stmt_calls(&function.body, &mut calls);
                let mut references = Vec::new();
                collect_stmt_function_references(&function.body, &mut references);
                graph.insert(
                    function.name.clone(),
                    calls
                        .into_iter()
                        .chain(references.into_iter().map(|name| vec![name]))
                        .filter_map(|path| resolve_called_function(&path, model))
                        .collect::<Vec<_>>(),
                );
                if function
                    .attrs
                    .iter()
                    .any(|attr| attr == "naked" || attr == "interrupt")
                {
                    roots.push(function.name.clone());
                }
            }
            Declaration::Global(global) => {
                let mut calls = Vec::new();
                collect_expr_calls(&global.value, &mut calls);
                roots.extend(
                    calls
                        .into_iter()
                        .filter_map(|path| resolve_called_function(&path, model)),
                );
                let mut references = Vec::new();
                collect_expr_function_references(&global.value, &mut references);
                roots.extend(
                    references
                        .into_iter()
                        .filter(|name| model.functions.contains_key(name)),
                );
            }
            _ => {}
        }
    }

    let mut reachable = HashSet::new();
    let mut pending = roots;
    while let Some(name) = pending.pop() {
        if !reachable.insert(name.clone()) {
            continue;
        }
        if let Some(calls) = graph.get(&name) {
            pending.extend(calls.iter().cloned());
        }
    }
    reachable
}

fn resolve_called_function(path: &[String], model: &SemanticModel) -> Option<String> {
    let qualified = path.join(".");
    if model.functions.contains_key(&qualified) {
        Some(qualified)
    } else {
        path.last()
            .filter(|name| model.functions.contains_key(*name))
            .cloned()
    }
}

fn collect_stmt_calls(stmts: &[Stmt], calls: &mut Vec<Vec<String>>) {
    for stmt in stmts {
        match stmt {
            Stmt::Let { value, .. }
            | Stmt::LetTwo { value, .. }
            | Stmt::Return(Some(value))
            | Stmt::Expr(value) => {
                collect_expr_calls(value, calls);
            }
            Stmt::ReturnTwo { first, second } => {
                collect_expr_calls(first, calls);
                collect_expr_calls(second, calls);
            }
            Stmt::Assign { target, value, .. } => {
                collect_place_calls(target, calls);
                collect_expr_calls(value, calls);
            }
            Stmt::If {
                condition,
                then_body,
                else_body,
            } => {
                collect_expr_calls(condition, calls);
                collect_stmt_calls(then_body, calls);
                collect_stmt_calls(else_body, calls);
            }
            Stmt::While { condition, body } => {
                collect_expr_calls(condition, calls);
                collect_stmt_calls(body, calls);
            }
            Stmt::Loop { body } => collect_stmt_calls(body, calls),
            Stmt::Out { value, .. } => collect_expr_calls(value, calls),
            Stmt::Return(None) | Stmt::Break | Stmt::Continue | Stmt::Asm { .. } => {}
        }
    }
}

fn collect_stmt_function_references(stmts: &[Stmt], references: &mut Vec<String>) {
    for stmt in stmts {
        match stmt {
            Stmt::Let { value, .. }
            | Stmt::LetTwo { value, .. }
            | Stmt::Return(Some(value))
            | Stmt::Expr(value)
            | Stmt::Out { value, .. } => {
                collect_expr_function_references(value, references);
            }
            Stmt::ReturnTwo { first, second } => {
                collect_expr_function_references(first, references);
                collect_expr_function_references(second, references);
            }
            Stmt::Assign { value, .. } => collect_expr_function_references(value, references),
            Stmt::If {
                condition,
                then_body,
                else_body,
            } => {
                collect_expr_function_references(condition, references);
                collect_stmt_function_references(then_body, references);
                collect_stmt_function_references(else_body, references);
            }
            Stmt::While { condition, body } => {
                collect_expr_function_references(condition, references);
                collect_stmt_function_references(body, references);
            }
            Stmt::Loop { body } => collect_stmt_function_references(body, references),
            Stmt::Return(None) | Stmt::Break | Stmt::Continue | Stmt::Asm { .. } => {}
        }
    }
}

fn collect_expr_function_references(expr: &Expr, references: &mut Vec<String>) {
    match expr {
        Expr::AddressOf(name) => references.push(name.clone()),
        Expr::Array(values) => values
            .iter()
            .for_each(|value| collect_expr_function_references(value, references)),
        Expr::Index { index, .. } | Expr::AddressOfIndex { index, .. } => {
            collect_expr_function_references(index, references)
        }
        Expr::Access(path) | Expr::AddressOfAccess(path) => {
            for segment in &path.segments {
                if let AccessSegment::Index(index) = segment {
                    collect_expr_function_references(index, references);
                }
            }
        }
        Expr::StructInit { fields, .. } => fields
            .iter()
            .for_each(|(_, value)| collect_expr_function_references(value, references)),
        Expr::Deref(value)
        | Expr::BankedPointer { pointer: value, .. }
        | Expr::Unary { expr: value, .. }
        | Expr::Cast { expr: value, .. } => collect_expr_function_references(value, references),
        Expr::Call { args, .. } => args
            .iter()
            .for_each(|arg| collect_expr_function_references(arg, references)),
        Expr::Binary { left, right, .. } => {
            collect_expr_function_references(left, references);
            collect_expr_function_references(right, references);
        }
        Expr::Int(_)
        | Expr::TypedInt(_, _)
        | Expr::Bool(_)
        | Expr::Char(_)
        | Expr::String(_)
        | Expr::Ident(_)
        | Expr::In(_)
        | Expr::Field { .. }
        | Expr::AddressOfField { .. } => {}
    }
}

fn collect_place_calls(place: &Place, calls: &mut Vec<Vec<String>>) {
    match place {
        Place::Index { index, .. } | Place::Deref(index) => collect_expr_calls(index, calls),
        Place::Access(path) => collect_access_path_calls(path, calls),
        Place::Ident(_) | Place::Field { .. } => {}
    }
}

fn collect_expr_calls(expr: &Expr, calls: &mut Vec<Vec<String>>) {
    match expr {
        Expr::Array(values) => {
            for value in values {
                collect_expr_calls(value, calls);
            }
        }
        Expr::Index { index, .. } | Expr::AddressOfIndex { index, .. } => {
            collect_expr_calls(index, calls);
        }
        Expr::Access(path) | Expr::AddressOfAccess(path) => collect_access_path_calls(path, calls),
        Expr::StructInit { fields, .. } => {
            for (_, value) in fields {
                collect_expr_calls(value, calls);
            }
        }
        Expr::Deref(value)
        | Expr::BankedPointer { pointer: value, .. }
        | Expr::Unary { expr: value, .. }
        | Expr::Cast { expr: value, .. } => {
            collect_expr_calls(value, calls);
        }
        Expr::Call { path, args } => {
            calls.push(path.clone());
            for arg in args {
                collect_expr_calls(arg, calls);
            }
        }
        Expr::Binary { left, right, .. } => {
            collect_expr_calls(left, calls);
            collect_expr_calls(right, calls);
        }
        Expr::Int(_)
        | Expr::TypedInt(_, _)
        | Expr::Bool(_)
        | Expr::Char(_)
        | Expr::String(_)
        | Expr::Ident(_)
        | Expr::In(_)
        | Expr::Field { .. }
        | Expr::AddressOfField { .. }
        | Expr::AddressOf(_) => {}
    }
}

fn collect_access_path_calls(path: &AccessPath, calls: &mut Vec<Vec<String>>) {
    for segment in &path.segments {
        if let AccessSegment::Index(index) = segment {
            collect_expr_calls(index, calls);
        }
    }
}

fn rewrite_local_labels(line: &str, prefix: &str) -> String {
    line.split_whitespace()
        .map(|token| {
            token
                .strip_prefix('.')
                .map(|local| format!(".{prefix}_{local}"))
                .unwrap_or_else(|| token.to_owned())
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn function_label(name: &str) -> String {
    format!("_{name}")
}

fn sanitize(name: &str) -> String {
    name.chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || ch == '_' {
                ch
            } else {
                '_'
            }
        })
        .collect()
}

