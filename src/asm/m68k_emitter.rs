const M68K_POINTER_CLASS: RegClass = RegClass(0);
const M68K_MEMORY_CLASS: RegClass = RegClass(1);
const M68K_STATIC_SPILL_CLASS: SpillClassId = SpillClassId(0);

fn m68k_local_target() -> Target {
    Target {
        units: M68K_ADDRESS_REGISTERS
            .iter()
            .map(|register| RegisterUnit::new(format!("a{register}")))
            .collect(),
        registers: M68K_ADDRESS_REGISTERS
            .iter()
            .enumerate()
            .map(|(unit, register)| {
                PhysicalRegister::new(format!("a{register}"), vec![RegUnit(unit)])
            })
            .collect(),
        register_classes: vec![
            RegisterClass::new(
                "pointer-address",
                (0..M68K_ADDRESS_REGISTERS.len()).map(PhysReg).collect(),
            ),
            RegisterClass::new("memory-local", Vec::new()),
        ],
        spill_classes: vec![
            SpillClass::new("static", None, 0)
                .for_register_classes(vec![M68K_POINTER_CLASS, M68K_MEMORY_CLASS]),
        ],
    }
}

fn plan_function_locals(
    function: &Function,
    model: &mut SemanticModel,
) -> Result<HashMap<String, Binding>, Diagnostic> {
    let mut source_locals = Vec::new();
    let mut local_types = HashMap::new();
    collect_source_locals(&function.body, model, &mut source_locals, &mut local_types)?;
    let clobbers = (0..M68K_ADDRESS_REGISTERS.len())
        .map(PhysReg)
        .collect::<Vec<_>>();
    let planned = allocate_source_locals(
        &m68k_local_target(),
        &source_locals,
        &function.body,
        &clobbers,
    )
    .map_err(regalloc_diagnostic)?;
    let spill_bytes = planned
        .allocation
        .spill_slots
        .iter()
        .map(|slot| slot.offset.saturating_add(slot.size))
        .max()
        .unwrap_or(0);
    let spill_region = model.allocate(spill_bytes)?;
    let mut bindings = HashMap::new();
    for (name, ty) in local_types {
        let vreg = planned
            .locals
            .vreg(&name)
            .ok_or_else(|| Diagnostic::new(format!("missing allocation for local `{name}`")))?;
        let location = match planned.allocation.location(vreg) {
            Some(Location::Register(register)) => {
                if !matches!(ty, Type::Ptr(_)) {
                    return Err(Diagnostic::new(format!(
                        "non-pointer local `{name}` was allocated to an address register"
                    )));
                }
                let register = *M68K_ADDRESS_REGISTERS.get(register.0).ok_or_else(|| {
                    Diagnostic::new(format!("invalid M68k local register for `{name}`"))
                })?;
                BindingLocation::AddressRegister(register)
            }
            Some(Location::Spill(slot_index)) => {
                let slot = planned
                    .allocation
                    .spill_slots
                    .get(slot_index)
                    .ok_or_else(|| Diagnostic::new(format!("invalid spill slot for `{name}`")))?;
                debug_assert_eq!(slot.class, M68K_STATIC_SPILL_CLASS);
                BindingLocation::Memory(Storage {
                    address: spill_region.address + slot.offset,
                    size: slot.size,
                })
            }
            Some(Location::Unused) | None => {
                return Err(Diagnostic::new(format!(
                    "source allocator did not place local `{name}`"
                )));
            }
        };
        bindings.insert(
            name,
            Binding {
                location,
                ty,
                volatile: false,
            },
        );
    }
    Ok(bindings)
}

fn collect_source_locals(
    body: &[Stmt],
    model: &SemanticModel,
    locals: &mut Vec<SourceLocal>,
    local_types: &mut HashMap<String, Type>,
) -> Result<(), Diagnostic> {
    for stmt in body {
        match stmt {
            Stmt::Let { name, ty, .. } => {
                let ty = model.resolved_type(ty)?;
                let pointer = matches!(ty, Type::Ptr(_));
                let class = if pointer {
                    M68K_POINTER_CLASS
                } else {
                    M68K_MEMORY_CLASS
                };
                if local_types.insert(name.clone(), ty.clone()).is_some() {
                    return Err(Diagnostic::new(format!("duplicate local `{name}`")));
                }
                locals.push(
                    SourceLocal::new(name.clone(), model.type_size(&ty)?, 1, class)
                        .with_spill_classes(vec![M68K_STATIC_SPILL_CLASS])
                        .with_force_memory(!pointer),
                );
            }
            Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_source_locals(then_body, model, locals, local_types)?;
                collect_source_locals(else_body, model, locals, local_types)?;
            }
            Stmt::While { body, .. } | Stmt::Loop { body } => {
                collect_source_locals(body, model, locals, local_types)?;
            }
            _ => {}
        }
    }
    Ok(())
}

fn regalloc_diagnostic(diagnostics: Vec<crate::regalloc::Diagnostic>) -> Diagnostic {
    Diagnostic::new(
        diagnostics
            .into_iter()
            .map(|diagnostic| diagnostic.message)
            .collect::<Vec<_>>()
            .join("; "),
    )
}

fn expr_call_args(expr: &Expr) -> Result<&[Expr], Diagnostic> {
    match expr {
        Expr::Call { args, .. } => Ok(args),
        _ => Err(Diagnostic::new("expected function call")),
    }
}

fn size_suffix(ty: &Type) -> Result<&'static str, Diagnostic> {
    match ty {
        Type::Named(name) if matches!(name.as_str(), "u8" | "i8" | "bool") => Ok("b"),
        Type::Named(name) if matches!(name.as_str(), "u16" | "i16") => Ok("w"),
        Type::Named(name) if matches!(name.as_str(), "u24" | "i24" | "ptr" | "u32" | "i32") => {
            Ok("l")
        }
        Type::Ptr(_) => Ok("l"),
        _ => Err(Diagnostic::new("unsupported M68k scalar type")),
    }
}

fn scalar_width(ty: &Type) -> Result<u8, Diagnostic> {
    match ty {
        Type::Named(name) if matches!(name.as_str(), "u8" | "i8" | "bool") => Ok(1),
        Type::Named(name) if matches!(name.as_str(), "u16" | "i16") => Ok(2),
        Type::Named(name) if matches!(name.as_str(), "u24" | "i24" | "ptr") => Ok(3),
        Type::Named(name) if matches!(name.as_str(), "u32" | "i32") => Ok(4),
        Type::Ptr(_) => Ok(3),
        _ => Err(Diagnostic::new("unsupported M68k scalar type")),
    }
}

fn width_mask(width: u8) -> u32 {
    match width {
        1 => 0xFF,
        2 => 0xFFFF,
        3 => 0xFF_FFFF,
        4 => 0xFFFF_FFFF,
        _ => unreachable!(),
    }
}

fn should_use_memory_shift(count: u32) -> bool {
    if count == 0 {
        return false;
    }
    let memory_cycles = 20 * count;
    let register_cycles = 28 + 8 + 2 * count;
    memory_cycles < register_cycles
}

fn match_rotate<'a, F>(expr: &'a Expr, bits: u32, shift_count: F) -> Option<(&'a Expr, u32)>
where
    F: Fn(&Expr) -> Option<u32>,
{
    let Expr::Binary {
        left,
        op: BinaryOp::BitOr,
        right,
    } = expr
    else {
        return None;
    };
    let shifted = |expr: &'a Expr| {
        let Expr::Binary { left, op, right } = expr else {
            return None;
        };
        matches!(op, BinaryOp::Shl | BinaryOp::Shr)
            .then(|| (left.as_ref(), *op, shift_count(right)))
            .and_then(|(source, op, count)| count.map(|count| (source, op, count)))
    };
    let first = shifted(left)?;
    let second = shifted(right)?;
    let (left_shift, right_shift) = match (first.1, second.1) {
        (BinaryOp::Shl, BinaryOp::Shr) => (first, second),
        (BinaryOp::Shr, BinaryOp::Shl) => (second, first),
        _ => return None,
    };
    (left_shift.0 == right_shift.0
        && left_shift.2 != 0
        && right_shift.2 != 0
        && left_shift.2 < bits
        && left_shift.2 + right_shift.2 == bits)
        .then_some((left_shift.0, left_shift.2))
}

fn flatten_bit_or<'a>(expr: &'a Expr, terms: &mut Vec<&'a Expr>) {
    if let Expr::Binary {
        left,
        op: BinaryOp::BitOr,
        right,
    } = expr
    {
        flatten_bit_or(left, terms);
        flatten_bit_or(right, terms);
    } else {
        terms.push(expr);
    }
}

fn shifted_mask_term<'a, F>(
    expr: &'a Expr,
    shift_count: F,
) -> Option<(&'a Expr, BinaryOp, u32, Option<u64>)>
where
    F: Fn(&Expr) -> Option<u32>,
{
    let Expr::Binary { left, op, right } = expr else {
        return None;
    };
    if !matches!(op, BinaryOp::Shl | BinaryOp::Shr) {
        return None;
    }
    let count = shift_count(right)?;
    let (source, mask) = match left.as_ref() {
        Expr::Binary {
            left: source,
            op: BinaryOp::BitAnd,
            right: mask,
        } => (
            source.as_ref(),
            Some(u64::try_from(const_expr_value(mask)?).ok()?),
        ),
        _ => (left.as_ref(), None),
    };
    Some((source, *op, count, mask))
}

fn const_expr_value(expr: &Expr) -> Option<i64> {
    match expr {
        Expr::Int(value) | Expr::TypedInt(value, _) => Some(*value),
        _ => None,
    }
}

fn match_u16_byte_swap<'a, F>(terms: &[&'a Expr], shift_count: F) -> Option<&'a Expr>
where
    F: Fn(&Expr) -> Option<u32> + Copy,
{
    if terms.len() != 2 {
        return None;
    }
    let mut left_source = None;
    let mut right_source = None;
    for term in terms {
        let (source, op, count, mask) = shifted_mask_term(term, shift_count)?;
        if count != 8 {
            return None;
        }
        match (op, mask) {
            (BinaryOp::Shl, None | Some(0xFF) | Some(0xFFFF)) if left_source.is_none() => {
                left_source = Some(source)
            }
            (BinaryOp::Shr, None | Some(0xFF00) | Some(0xFFFF)) if right_source.is_none() => {
                right_source = Some(source)
            }
            _ => return None,
        }
    }
    let left_source = left_source?;
    let right_source = right_source?;
    (left_source == right_source).then_some(left_source)
}

fn match_u32_byte_swap<'a, F>(terms: &[&'a Expr], shift_count: F) -> Option<&'a Expr>
where
    F: Fn(&Expr) -> Option<u32> + Copy,
{
    if terms.len() != 4 {
        return None;
    }
    let expected = [
        (BinaryOp::Shl, 24_u32, 0xFF_u64),
        (BinaryOp::Shl, 8_u32, 0xFF00_u64),
        (BinaryOp::Shr, 8_u32, 0xFF0000_u64),
        (BinaryOp::Shr, 24_u32, 0xFF000000_u64),
    ];
    let mut source = None;
    let mut found = [false; 4];
    for term in terms {
        let (term_source, op, count, Some(mask)) = shifted_mask_term(term, shift_count)? else {
            return None;
        };
        let Some(index) =
            expected
                .iter()
                .position(|(expected_op, expected_count, expected_mask)| {
                    *expected_op == op && *expected_count == count && *expected_mask == mask
                })
        else {
            return None;
        };
        if found[index] {
            return None;
        }
        found[index] = true;
        if let Some(source) = source {
            if source != term_source {
                return None;
            }
        } else {
            source = Some(term_source);
        }
    }
    found.into_iter().all(|found| found).then_some(source?)
}

fn element_type(ty: &Type) -> Result<Type, Diagnostic> {
    match ty {
        Type::Array { element, .. } | Type::Ptr(element) => Ok((**element).clone()),
        _ => Err(Diagnostic::new("indexing requires array or pointer")),
    }
}

fn type_is_signed(ty: &Type) -> bool {
    matches!(ty, Type::Named(name) if name.starts_with('i'))
}
fn is_comparison(op: BinaryOp) -> bool {
    matches!(
        op,
        BinaryOp::Eq | BinaryOp::Ne | BinaryOp::Lt | BinaryOp::Le | BinaryOp::Gt | BinaryOp::Ge
    )
}
fn comparison_branch(op: BinaryOp, signed: bool) -> &'static str {
    match (op, signed) {
        (BinaryOp::Eq, _) => "beq",
        (BinaryOp::Ne, _) => "bne",
        (BinaryOp::Lt, true) => "blt",
        (BinaryOp::Le, true) => "ble",
        (BinaryOp::Gt, true) => "bgt",
        (BinaryOp::Ge, true) => "bge",
        (BinaryOp::Lt, false) => "bcs",
        (BinaryOp::Le, false) => "bls",
        (BinaryOp::Gt, false) => "bhi",
        (BinaryOp::Ge, false) => "bcc",
        _ => unreachable!(),
    }
}
fn assign_binary(op: AssignOp) -> BinaryOp {
    match op {
        AssignOp::Add => BinaryOp::Add,
        AssignOp::Sub => BinaryOp::Sub,
        AssignOp::Mul => BinaryOp::Mul,
        AssignOp::Div => BinaryOp::Div,
        AssignOp::Mod => BinaryOp::Mod,
        AssignOp::BitAnd => BinaryOp::BitAnd,
        AssignOp::BitOr => BinaryOp::BitOr,
        AssignOp::BitXor => BinaryOp::BitXor,
        AssignOp::Shl => BinaryOp::Shl,
        AssignOp::Shr => BinaryOp::Shr,
        AssignOp::Set => unreachable!(),
    }
}
fn function_label(name: &str) -> String {
    format!("_{}", sanitize(name))
}
fn sanitize(name: &str) -> String {
    name.chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || ch == '_' {
                ch
            } else {
                '_'
            }
        })
        .collect()
}

